def quote(value: str) -> str:
    return json.dumps(value)


def action_sizes() -> dict[str, dict[str, int]]:
    if not ACTION_SIZES_PATH.exists():
        return {}
    return json.loads(ACTION_SIZES_PATH.read_text(encoding="utf-8"))


ACTION_SIZES = action_sizes()


def exec_properties(crate_name: str, kind: str) -> dict[str, str]:
    """The remote request for one target, or nothing when it is the default.

    Both keys are emitted together whenever either exceeds its default, so a
    sized target states its whole request instead of stating one half and
    inheriting the other.
    """
    key = f"{crate_name}/{kind}"
    entry = ACTION_SIZES.get(key) or {}
    cpu_count = entry.get("cpu_count", DEFAULT_CPU_COUNT)
    if kind in TEST_SIZE_KINDS:
        cpu_count = max(cpu_count, TEST_CPU_FLOOR)
    cpu_count = max(cpu_count, CPU_FLOORS.get(key, 0))
    memory_kb = entry.get("memory_kb", DEFAULT_MEMORY_KB)
    # Whether to emit at all is decided on the measured request: a target that
    # wants no more than this repository's own defaults states nothing and
    # inherits whatever the invocation supplies.
    if cpu_count <= DEFAULT_CPU_COUNT and memory_kb <= DEFAULT_MEMORY_KB:
        return {}
    # Emitting either resource also preserves the sized-target safety floor
    # for the other. These floors do not change with invocation defaults.
    return {
        "cpu_count": str(max(cpu_count, SIZED_CPU_FLOOR)),
        "memory_kb": str(max(memory_kb, SIZED_MEMORY_FLOOR)),
    }


def exec_properties_argument(crate_name: str, kind: str, indent: int = 4) -> str:
    """Renders the `exec_properties = {...}` line, or nothing."""
    properties = exec_properties(crate_name, kind)
    if not properties:
        return ""
    spaces = " " * indent
    return f"{spaces}exec_properties = {json.dumps(properties, sort_keys=True)},\n"


def string_list(values: list[str], indent: int = 8) -> str:
    if not values:
        return "[]"
    spaces = " " * indent
    return "[\n" + "".join(f"{spaces}{quote(value)},\n" for value in values) + " " * (indent - 4) + "]"


