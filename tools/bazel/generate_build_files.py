def target_support(
    package: dict,
    targets: list[dict],
    target: dict,
    kind: str,
) -> tuple[list[str], list[str], dict[str, str], list[str]]:
    """The per-target sandbox inputs, runtime inputs, test env and skips.

    Extracted verbatim from the ordinary target loop so the feature-lane
    variants of the same Cargo target carry exactly the same support data;
    a variant that dropped one of these would pass by seeing nothing.
    """
    test_env: dict[str, str] = {}
    extra_data = []
    if (
        package["name"] == "lash-internal-core"
        and target["name"] == "integration_boundary"
    ):
        # The checked-in workspace fact that replaces a nested
        # `cargo metadata` call in the dependency-direction test.
        extra_data.append("//tools/bazel:target_inventory")
    if package["name"] == "lash-internal-core" and target["name"] in (
        "runtime_turns",
        "runtime_observability",
    ):
        # These carry the relocated suites that assert over captured
        # `tracing` events. Capture installs a scoped default subscriber,
        # so other cases in the same libtest process must not emit
        # concurrently; Cargo nextest isolates by process, Bazel does not.
        test_env["RUST_TEST_THREADS"] = "1"
    if package["name"] == "lash-internal-sqlite-store" and target["name"] == "integration":
        # The warning-capture contract installs a scoped tracing subscriber.
        # Other tests in this libtest process must not emit concurrently.
        test_env["RUST_TEST_THREADS"] = "1"
    if package["name"] == "lash-internal-lashlang" and target["name"] in (
        "append_cost",
        "dialect_cost",
    ):
        # These cost laws read a process-global counting allocator. Cargo
        # nextest isolates cases by process; serialize libtest so Bazel
        # observes the same one-at-a-time measurement contract.
        test_env["RUST_TEST_THREADS"] = "1"
    extra_compile_data = []
    if package["name"] in (
        "agent-service",
        "agent-workbench",
        "slack-clone",
        "toolbench",
    ):
        extra_compile_data.append("//examples:shared_rust_sources")
    if (
        package["name"] == "lash-internal-typescript"
        and target["name"] == "integration"
    ):
        # The codemode parity module links the checked-in
        # `examples/codemode-parity/*.ts` cells with `include_str!`, so the
        # cells are compile inputs of this test and of no other.
        extra_compile_data.append("//examples:codemode_parity_cells")
        # The schema agreement test compiles the published graph schema into
        # the test and validates real serialized graph documents against it.
        extra_compile_data.append("//:workflow_graph_schema")
    if package["name"] == "lash-internal-lashlang" and target["name"] == "dialect_cost":
        # It holds the dialect to the corpus's own checked-in budget by
        # reading the budget file with `include_str!`, the way lash-perf
        # does, so the file is a compile input of this test.
        extra_compile_data.append("//:perf_guard_budgets")
    if package["name"] in (
        "lash-internal-postgres-store",
        "lash-internal-sqlite-store",
    ):
        if target["name"] == "conformance":
            helper_name = (
                "postgres-await-event-helper"
                if package["name"] == "lash-internal-postgres-store"
                else "sqlite-await-event-helper"
            )
            helper_target = next(
                candidate for candidate in targets if candidate["name"] == helper_name
            )
            helper_label = f":{label_name(helper_target, False)}"
            test_env["LASH_CONFORMANCE_HELPER_EXE"] = (
                f"$(rootpath {helper_label})"
            )
            extra_data.append(helper_label)
        if target["name"] in (
            "postgres-await-event-helper",
            "sqlite-await-event-helper",
        ):
            extra_compile_data.append("//crates/lash-core:cold_process_drivers")
        if target["name"] == "conformance":
            extra_compile_data.extend([
                "//crates/lash-core:queued_claim_atomicity",
            ])
        if target["name"] == "durable_read_fixture":
            extra_compile_data.append("//crates/lash-core:durable_read_fixture_source")
            extra_data.append("//crates/lash-core:durable_read_predecessor_fixtures")
    if (
        package["name"] == "lash-internal-postgres-store"
        and target["name"] == "preflight_durable_walk"
    ):
        extra_compile_data.append("//crates/lashlang:old_module_fixture")
    if package["name"] in (
        "lash-internal-postgres-store",
        "lash-internal-sqlite-store",
    ) and target["name"] == "durable_read_fixture":
        extra_compile_data.append("//:durable_fixtures")
    # Architecture lints that read sibling crates' sources at run time. A
    # library's runfiles carry only its non-Rust package files (a `.rs` is a
    # compile input, not a runtime one), so a test that scans another crate's
    # sources names that crate's `rust_sources` filegroup here; every other
    # test stops re-running when an unrelated crate's test file changes.
    if package["name"] == "lash-internal-core" and target["name"] in (
        "runtime_effect",
        "runtime_scenarios",
    ):
        extra_data.append("//crates/lash-core-execution:rust_sources")
    if package["name"] == "lash-runtime" and target["name"] == "facade_inventory":
        extra_data.extend([
            "//crates/lash-remote-protocol:rust_sources",
            "//crates/lash-sansio:rust_sources",
            "//crates/lash-tool-support:rust_sources",
            "//crates/lash-trace:rust_sources",
        ])
    target_args = []
    if (
        package["name"] == "lash-internal-core"
        and target["name"] == "runtime_scenarios"
    ):
        # The fault-matrix routing probes execute the real
        # scripts/confidence-gate.sh against a recording `cargo`.
        extra_data.append("//:confidence_gate_scripts")
        # The five `..._real_cargo_filters_chunk_*` cases each fork a real
        # `cargo test ... -- --list` against the workspace to prove the
        # gate's name filters still select tests. That is a claim about
        # Cargo's own selection, so it cannot be proved inside a hermetic
        # action without Cargo; the trunk-only `Test heavy suites` job
        # (profile.ci-heavy) owns them and is the only place they run.
        # Excluded by name here so the label is honest about what it
        # executed.
        target_args.append(
            "--skip=runtime::tests::runtime_scenarios::fault_matrix"
            "::durable_fault_matrix_real_cargo_filters_chunk_"
        )
    if package["name"] == "lash-sim" and kind == "test":
        extra_compile_data.extend([
            "//crates/lash-postgres-store:package_files",
            "//crates/lash-sqlite-store:package_files",
        ])
        if target["name"] == "cross_backend_store_differential":
            # Its completeness gates read the real store trait definitions
            # with `include_str!`, so the lash-core-store sources are
            # compile inputs of this test and of no other lash-sim test.
            extra_compile_data.append(
                "//crates/lash-core-store:package_files"
            )
    if (
        package["name"] == "lash-sim"
        and target["name"] == "signal_replay_key_constructor"
    ):
        # The gate scans every first-party Rust source, runbooks and
        # examples included, so under Bazel it needs them all in the sandbox
        # or it would pass by seeing nothing.
        extra_compile_data.append("//:workspace_rust_sources")
    return extra_compile_data, extra_data, test_env, target_args


def render_package(package: dict, features: list[str]) -> tuple[str, dict]:
    manifest = relative(package["manifest_path"])
    package_dir = pathlib.PurePosixPath(manifest).parent.as_posix()
    version = package["version"]
    declared_features = sorted(package["features"])
    targets = [target for target in package["targets"] if "custom-build" not in target["kind"]]
    resolved_feature_set = set(features)

    def enabled_by_resolved_features(target: dict) -> bool:
        return set(target.get("required-features", [])) <= resolved_feature_set

    library = next((target for target in targets if "lib" in target["kind"]), None)
    binaries = [target for target in targets if "bin" in target["kind"]]
    binary_labels = {
        target["name"]: label_name(target, library is None and len(binaries) == 1)
        for target in binaries
        if enabled_by_resolved_features(target)
    }
    primary_target = pathlib.PurePosixPath(package_dir).name
    doc_label = None
    library_label = f":{primary_target}" if library else None
    library_crate = library["name"] if library else None
    chunks = [GENERATED_HEADER, LOAD]
    if library:
        chunks.append('load("@rules_rust//rust:defs.bzl", "rust_doc")\n\n')
    chunks.append("package(default_visibility = [\"//visibility:public\"])\n\n")
    inventory_targets = []
    # FIG-3365: plain libtest binaries (no args/env/shards/timeout/policy
    # tags) join the package's `lash_batch_test` instead of paying a runfiles
    # forest and TestRunner action each.
    batch_members = []

    has_build_script = any("custom-build" in target["kind"] for target in package["targets"])
    if has_build_script:
        chunks.append(
            "lash_rust_build_script(\n"
            "    name = \"build_script\",\n"
            f"    crate_features = {string_list(features)},\n"
            f"    declared_features = {string_list(declared_features)},\n"
            f"    data = [\"{relative(next(target for target in package['targets'] if 'custom-build' in target['kind'])['src_path']).replace(package_dir + '/', '')}\"] + glob([\"src/**/*.rs\"]),\n"
            # Keyed by package: `cargo_build_script` can only size the action
            # that RUNS the script, and that action is one per package. Every
            # `build.rs` COMPILE shares the crate name `build_script_build`,
            # which is why the compile is not sizeable from here.
            + exec_properties_argument(package["name"], "build-script")
            + f"    manifest_dir = {quote(package_dir)},\n"
            f"    package_name = {quote(package['name'])},\n"
            f"    version = {quote(version)},\n"
            ")\n\n"
        )
        inventory_targets.append({
            # The label that RUNS the script. `cargo_build_script` exposes no
            # `CrateInfo` here, so the clippy aspect cannot attach to it -- but
            # running a script is not a compilation and has no lints of its own.
            # The `build.rs` compile is the lintable half, and it is the
            # `:build_script_` target below (FIG-3176).
            "clippy_exempt": "the run action has no CrateInfo; its build.rs compile is linted as :build_script_",
            "kind": "custom-build",
            "label": f"//{package_dir}:build_script",
        })
        inventory_targets.append({
            # `cargo_build_script` declares the `build.rs` compile as a
            # `rust_binary` named `<name>_`. It carries `CrateInfo`, so the
            # clippy aspect does attach, and linting it is what makes the Bazel
            # partition match `cargo clippy --all-targets` on build scripts.
            "kind": "custom-build-compile",
            "label": f"//{package_dir}:build_script_",
            "tags": ["manual"],
        })

    if library:
        extra_compile_data = library_compile_data(package["name"])
        chunks.append(
            "lash_rust_library(\n"
            f"    name = {quote(primary_target)},\n"
            f"    build_script = {quote(':build_script') if has_build_script else 'None'},\n"
            f"    crate_features = {string_list(features)},\n"
            f"    crate_name = {quote(library['name'])},\n"
            f"    declared_features = {string_list(declared_features)},\n"
            + exec_properties_argument(library["name"], "lib")
            + library_test_sources_argument(package_dir)
            + library_data_patterns_argument(package_dir)
            + f"    extra_compile_data = {string_list(extra_compile_data)},\n"
            f"    manifest_dir = {quote(package_dir)},\n"
            f"    package_name = {quote(package['name'])},\n"
            f"    version = {quote(version)},\n"
            ")\n\n"
        )
        # `cargo doc` documents each library crate; rust_doc resolves the
        # crate's own deps transitively from its CrateInfo, so one target per
        # library reproduces the workspace doc build.
        chunks.append(
            "rust_doc(\n"
            f"    name = {quote(primary_target + '__doc')},\n"
            f"    crate = {quote(':' + primary_target)},\n"
            "    testonly = True,\n"
            ")\n\n"
        )
        doc_label = f"//{package_dir}:{primary_target}__doc"
        inventory_targets.append({"kind": "lib", "cargo": library["name"], "label": f"//{package_dir}:{primary_target}"})
        if library.get("test", False):
            unit_compile_data = unit_test_compile_data(package["name"])
            unit_tags, unit_cargo_reason = cargo_test_policy(
                package["name"], "unit-test", library["name"]
            )
            unit_extra_data = []
            unit_args = []
            unit_timeout = None
            if package["name"] == "lash-sim":
                # The Postgres effect-history consistency case reads the gate
                # script and the repository-root documents it must agree with.
                unit_extra_data.append("//:confidence_gate_corpus")
                # This binary carries the generated-simulation and minimizer
                # fixture replays (measured 182-418 s each under Cargo). The
                # whole binary ran 227-300 s on the pool, which straddles
                # Bazel's default `medium` 300 s bound; `long` is 900 s.
                unit_timeout = "long"
            unit_shards = bazel_test_shard_count(
                package["name"], "unit-test", library["name"]
            )
            unit_test_env = {}
            if package["name"] == "lash-perf":
                # This instrumentation binary shares process-global counters.
                # Cargo nextest isolates cases by process; serialize libtest so
                # Bazel observes the same one-at-a-time measurement contract.
                unit_test_env["RUST_TEST_THREADS"] = "1"
            chunks.append(
                "lash_rust_unit_test(\n"
                f"    name = {quote(primary_target + '__unit_test')},\n"
                + (f"    args = {string_list(unit_args)},\n" if unit_args else "")
                + f"    build_script = {quote(':build_script') if has_build_script else 'None'},\n"
                f"    crate_features = {string_list(features)},\n"
                f"    crate_name = {quote(library['name'])},\n"
                f"    crate_root = {quote(relative(library['src_path']).replace(package_dir + '/', ''))},\n"
                f"    declared_features = {string_list(declared_features)},\n"
                + exec_properties_argument(library["name"], "test")
                + unit_test_sources_argument(package_dir)
                + f"    extra_compile_data = {string_list(unit_compile_data)},\n"
                + (
                    f"    extra_data = {string_list(unit_extra_data)},\n"
                    if unit_extra_data
                    else ""
                )
                + f"    manifest_dir = {quote(package_dir)},\n"
                + f"    package_name = {quote(package['name'])},\n"
                + (f"    shard_count = {unit_shards},\n" if unit_shards else "")
                + (
                    f"    test_env = {json.dumps(unit_test_env, sort_keys=True)},\n"
                    if unit_test_env
                    else ""
                )
                + f"    tags = {string_list(unit_tags)},\n"
                + (f"    timeout = {quote(unit_timeout)},\n" if unit_timeout else "")
                + f"    version = {quote(version)},\n"
                + ")\n\n"
            )
            if (
                not unit_args
                and not unit_test_env
                and not unit_shards
                and not unit_timeout
                and not unit_tags
            ):
                # FIG-3365: a plain unit test -- no args, env, sharding,
                # timeout, or policy tags -- rides the package's shared
                # `lash_batch_test` instead of paying its own runfiles forest
                # and test-runner action.
                batch_members.append(f":{primary_target}__unit_test")
            unit_inventory = {
                "cargo": library["name"],
                "kind": "unit-test",
                "label": f"//{package_dir}:{primary_target}__unit_test",
                "tags": unit_tags,
            }
            if unit_shards:
                unit_inventory["shard_count"] = unit_shards
            if unit_cargo_reason:
                unit_inventory["cargo_only"] = unit_cargo_reason
            inventory_targets.append(unit_inventory)
    for target in targets:
        kind = target["kind"][0]
        if kind == "lib":
            continue
        required_features = sorted(target.get("required-features", []))
        if not enabled_by_resolved_features(target):
            inventory_targets.append({
                "cargo": target["name"],
                "cargo_only": "required features are outside the resolved default workspace graph",
                "kind": kind,
                "label": None,
                "required_features": required_features,
                "tags": ["cargo-feature-gate", "manual"],
            })
            continue
        primary = not library and kind == "bin" and len(binaries) == 1
        name = label_name(target, primary)
        crate_root = relative(target["src_path"]).replace(package_dir + "/", "")
        target_features = sorted(set(features) | set(target.get("required-features", [])))
        source = pathlib.Path(target["src_path"])
        rustc_env, binary_data = cargo_bin_env(source, binary_labels)
        test_env = {}
        test_env.update(rustc_env)
        (
            extra_compile_data,
            extra_data,
            support_test_env,
            target_args,
        ) = target_support(package, targets, target, kind)
        test_env.update(support_test_env)
        macro = (
            "lash_rust_binary"
            if kind in ("bin", "example", "bench")
            else "lash_rust_integration_test"
        )
        crate_name = target["name"].replace("-", "_")
        target_tags, target_cargo_reason = cargo_test_policy(
            package["name"], kind, target["name"]
        )
        target_shards = bazel_test_shard_count(package["name"], kind, target["name"])
        if kind == "bench":
            target_tags.append("manual")
        # A `bench` is the only Cargo kind here that is not its own action
        # shape: the one bench in this workspace sets `harness = false`, so
        # rustc compiles it as a plain binary and it is measured as one.
        size_kind = "bin" if kind in ("bin", "example", "bench") else "test"
        args = [
            f"    name = {quote(name)},",
            f"    crate_features = {string_list(target_features)},",
            f"    crate_name = {quote(crate_name)},",
            f"    crate_root = {quote(crate_root)},",
            f"    declared_features = {string_list(declared_features)},",
        ]
        if kind == "test" and target["name"] in SOURCE_OWNERSHIP.get(package_dir, {}).get("tests", {}):
            args.append(f"    srcs_patterns = {string_list(test_source_patterns(package_dir, target['name']))},")
        sized = exec_properties_argument(crate_name, size_kind)
        if sized:
            args.append(sized.rstrip("\n"))
        args.append(
            f"    extra_compile_data = {string_list(extra_compile_data + binary_data)},"
        )
        if kind in ("bin", "example", "bench"):
            args.append(f"    include_dev_deps = {str(kind in ('example', 'bench'))},")
        else:
            if target_args:
                args.append(f"    args = {string_list(target_args)},")
            if extra_data:
                args.append(f"    extra_data = {string_list(extra_data)},")
            if target_shards:
                args.append(f"    shard_count = {target_shards},")
            if test_env:
                args.append(f"    test_env = {json.dumps(test_env, sort_keys=True)},")
        args.extend([
            f"    library = {quote(library_label) if library_label else 'None'},",
            f"    library_crate_name = {quote(library_crate) if library_crate else 'None'},",
            f"    manifest_dir = {quote(package_dir)},",
            f"    package_name = {quote(package['name'])},",
            f"    rustc_env = {json.dumps(rustc_env, sort_keys=True)},",
            f"    tags = {string_list(sorted(set(target_tags)))},",
            f"    version = {quote(version)},",
        ])
        chunks.append(macro + "(\n" + "\n".join(args) + "\n)\n\n")
        if package["name"] == "lash-runtime" and name == "ui__test":
            # FIG-3364: the trusted seal lane compiles every tests/ui/*.stderr
            # fixture with the toolchain rustc directly (ui_fixtures_test)
            # instead of trybuild's nested `cargo check`. The rule reads this
            # harness's CrateInfo/DepInfo, so fixtures see the identical
            # `--extern` set and feature resolution; the `.stderr` pins stay
            # shared with the untrusted `cargo test --test ui` path.
            #
            # The fixture set mirrors the registration gates in tests/ui.rs:
            # rlm-gated fixtures exist only when `rlm` resolves, and the two
            # store-seam pins are written for the isolated rlm-without-testing
            # graph (the `testing` feature changes the rendered qualified Pin
            # path), so they stay excluded under the canonical resolution.
            ui_rlm_gated = {
                "rlm_turn_options_cannot_name_a_dialect",
                "rlm_memory_limit_cannot_take_an_instruction_budget",
                "rlm_execution_bounds_are_not_swappable",
                "rlm_config_builder_requires_every_bound",
                "rlm_config_builder_requires_channel",
            }
            ui_store_seam = {
                "attachment_store_head_has_no_default",
                "session_store_factory_requires_deletion_answer",
            }
            ui_dir = ROOT / package_dir / "tests" / "ui"
            fixtures = sorted(p.stem for p in ui_dir.glob("*.stderr"))
            if "rlm" not in target_features:
                fixtures = [f for f in fixtures if f not in ui_rlm_gated]
            if "rlm" not in target_features or "testing" in target_features:
                fixtures = [f for f in fixtures if f not in ui_store_seam]
            chunks.append(
                'load("//tools/bazel:ui_fixtures.bzl", "ui_fixtures_test")\n\n'
                "ui_fixtures_test(\n"
                "    name = \"ui_fixtures\",\n"
                "    harness = \":ui__test\",\n"
                "    package = \"crates/lash\",\n"
                f"    fixtures = {string_list([f'tests/ui/{f}.rs' for f in fixtures])},\n"
                f"    expected = {string_list([f'tests/ui/{f}.stderr' for f in fixtures])},\n"
                '    tags = ["manual"],\n'
                ")\n\n"
            )
        if (
            kind == "test"
            and not target_args
            and not test_env
            and not target_shards
            and not target_tags
        ):
            batch_members.append(f":{name}")
        target_inventory = {
            "cargo": target["name"],
            "kind": kind,
            "label": f"//{package_dir}:{name}",
            "tags": sorted(set(target_tags)),
        }
        if target_shards:
            target_inventory["shard_count"] = target_shards
        if target_cargo_reason:
            target_inventory["cargo_only"] = target_cargo_reason
        inventory_targets.append(target_inventory)

        if kind == "bin" and target.get("test", False):
            bin_unit_tags, bin_unit_cargo_reason = cargo_test_policy(
                package["name"], "bin-unit-test", target["name"]
            )
            bin_unit_skips = (
                list(NODE_GATED_WORKBENCH_TESTS)
                if package["name"] == "agent-workbench"
                else []
            )
            unit_args = [
                "lash_rust_unit_test(\n",
                f"    name = {quote(name + '__unit_test')},\n",
            ]
            if bin_unit_skips:
                unit_args.append(
                    "    args = "
                    + string_list([f"--skip={test}" for test in bin_unit_skips])
                    + ",\n"
                )
            unit_args += [
                f"    crate_features = {string_list(target_features)},\n",
                f"    crate_name = {quote(crate_name)},\n",
                f"    crate_root = {quote(crate_root)},\n",
                f"    declared_features = {string_list(declared_features)},\n",
            ]
            bin_unit_sized = exec_properties_argument(crate_name, "test")
            if bin_unit_sized:
                unit_args.append(bin_unit_sized)
            if extra_compile_data or binary_data:
                unit_args.append(
                    f"    extra_compile_data = {string_list(extra_compile_data + binary_data)},\n"
                )
            unit_args.extend([
                f"    library = {quote(library_label) if library_label else 'None'},\n"
                f"    library_crate_name = {quote(library_crate) if library_crate else 'None'},\n"
                f"    manifest_dir = {quote(package_dir)},\n"
                f"    package_name = {quote(package['name'])},\n"
                f"    tags = {string_list(bin_unit_tags)},\n"
                f"    version = {quote(version)},\n"
                ")\n\n"
            ])
            chunks.append("".join(unit_args))
            bin_unit_inventory = {
                "cargo": target["name"],
                "kind": "bin-unit-test",
                "label": f"//{package_dir}:{name}__unit_test",
                "tags": bin_unit_tags,
            }
            if bin_unit_skips:
                bin_unit_inventory["bazel_skipped"] = sorted(bin_unit_skips)
            if bin_unit_cargo_reason:
                bin_unit_inventory["cargo_only"] = bin_unit_cargo_reason
            inventory_targets.append(bin_unit_inventory)
            if not bin_unit_skips and not bin_unit_tags:
                batch_members.append(f":{name}__unit_test")

    if package["name"] == "lash-internal-core":
        chunks.append(
            "filegroup(\n"
            "    name = \"cold_process_drivers\",\n"
            "    srcs = [\n"
            "        \"tests/support/cold_process_effect_driver.rs\",\n"
            "    ],\n"
            ")\n\n"
            "filegroup(\n"
            "    name = \"durable_read_fixture_source\",\n"
            "    srcs = [\"tests/support/durable_read_fixture.rs\"],\n"
            ")\n\n"
            "filegroup(\n"
            "    name = \"durable_read_predecessor_fixtures\",\n"
            "    srcs = glob([\"tests/fixtures/durable-read-predecessors/**\"]),\n"
            ")\n\n"
            "filegroup(\n"
            "    name = \"queued_claim_atomicity\",\n"
            "    srcs = [\"tests/support/queued_claim_atomicity.rs\"],\n"
            ")\n\n"
        )

    if package["name"] == "lash-internal-lashlang":
        chunks.append(
            "filegroup(\n"
            "    name = \"old_module_fixture\",\n"
            "    srcs = [\"tests/fixtures/module-artifact-old.json\"],\n"
            ")\n\n"
        )

    # One batch is only worth its wrapper action when it replaces at least
    # two per-test runfiles forests.
    batch_label = None
    if len(batch_members) >= 2:
        batch_label = f"//{package_dir}:test_batch"
        chunks.append(
            'load("//tools/bazel:test_batch.bzl", "lash_batch_test")\n\n'
            "lash_batch_test(\n"
            '    name = "test_batch",\n'
            f"    tests = {string_list(sorted(batch_members))},\n"
            ")\n\n"
        )

    chunks.append(
        "filegroup(\n"
        "    name = \"rust_sources\",\n"
        "    srcs = glob([\"**/*.rs\"]),\n"
        ")\n\n"
        "filegroup(\n"
        "    name = \"package_files\",\n"
        "    srcs = glob([\"**\"], exclude = [\"BUILD\", \"BUILD.bazel\"]),\n"
        ")\n"
    )
    return "".join(chunks), {
        "declared_features": declared_features,
        # Every declared dependency name of this package, normal, dev and build
        # alike — exactly what `cargo metadata --no-deps` reports for it.
        # Checked in so an architecture test can assert dependency direction
        # without shelling out to Cargo from inside a hermetic test action.
        "dependencies": sorted(
            {dependency["name"] for dependency in package["dependencies"]}
        ),
        "doc": doc_label,
        "manifest": manifest,
        "package": package["name"],
        "resolved_features": features,
        "targets": inventory_targets,
        "test_batch": {
            "label": batch_label,
            "members": (
                sorted(f"//{package_dir}{member}" for member in batch_members)
                if batch_label
                else []
            ),
        },
    }


def generated(metadata: dict) -> tuple[dict[pathlib.Path, str], list[dict]]:
    validate_source_ownership(metadata)
    features = package_features(metadata)
    outputs = {}
    inventory = []
    workspace_members = set(metadata["workspace_members"])
    for package in metadata["packages"]:
        manifest = pathlib.Path(package["manifest_path"]).resolve()
        if package["id"] not in workspace_members:
            continue
        content, item = render_package(package, features[package["id"]])
        outputs[manifest.parent / "BUILD.bazel"] = content
        inventory.append(item)
    inventory.sort(key=lambda item: item["manifest"])
    inventory_payload = {
        "cargo_package_count": len(inventory),
        "cargo_target_count": sum(
            1
            for package in metadata["packages"]
            if package["id"] in workspace_members
            for _target in package["targets"]
        ),
        "generated_label_count": sum(
            1
            for item in inventory
            for target in item["targets"]
            if target["label"] is not None
        ),
        "cargo_only_target_count": sum(
            1
            for item in inventory
            for target in item["targets"]
            if target["label"] is None
        ),
        "packages": inventory,
    }
    outputs[ROOT / "tools/bazel/target-inventory.json"] = (
        json.dumps(inventory_payload, indent=2, sort_keys=True) + "\n"
    )
    labels = [target for package in inventory for target in package["targets"]]
    executable_tests = [
        target
        for target in labels
        if target["label"] is not None
        and target["kind"] in ("bin-unit-test", "test", "unit-test")
    ]
    groups = {
        "WORKSPACE_COMPILE_TARGETS": sorted(
            target["label"] for target in labels if target["label"] is not None
        ),
        # Cargo lints libs, bins, examples, benches and test crates under
        # `clippy --workspace --all-targets`, build scripts included. Only the
        # label that RUNS a build script is excluded here -- it exposes no
        # `CrateInfo` and compiles nothing -- and its exemption reason is
        # recorded per label in `tools/bazel/target-inventory.json`. The
        # `build.rs` compile itself is linted through its `:build_script_`
        # target (FIG-3176).
        "WORKSPACE_CLIPPY_TARGETS": sorted(
            target["label"]
            for target in labels
            if target["label"] is not None
            and target["kind"] != "custom-build"
        ),
        # One rust_doc target per library crate: the `cargo doc --workspace`
        # shape as cached Bazel actions.
        "WORKSPACE_DOC_TARGETS": sorted(
            item["doc"] for item in inventory if item["doc"] is not None
        ),
        "WORKSPACE_RUST_SOURCE_TARGETS": sorted(
            f"//{pathlib.PurePosixPath(package['manifest']).parent.as_posix()}:rust_sources"
            for package in inventory
        ),
        "WORKSPACE_BAZEL_TEST_TARGETS": sorted(
            target["label"]
            for target in executable_tests
            if "manual" not in target["tags"] and "pr-deferred" not in target["tags"]
        ),
        # FIG-3365: what `//:workspace_tests` literally contains. Member-level
        # coverage is `WORKSPACE_BAZEL_TEST_TARGETS`; this list swaps each
        # package's plain tests for its `:test_batch` aggregate, so the
        # partition pays one runfiles forest per package instead of one per
        # binary. `WORKSPACE_TEST_BATCHES` is the contract-test handle for
        # reconciling members to batches.
        "WORKSPACE_TEST_SUITE_LABELS": None,  # computed below
        "WORKSPACE_DEV_SUITE_LABELS": None,  # computed below
        "WORKSPACE_TAIL_SUITE_LABELS": None,  # computed below
        "WORKSPACE_DEV_TEST_TARGETS": sorted(
            target["label"]
            for target in executable_tests
            if "manual" not in target["tags"]
            and "pr-deferred" not in target["tags"]
            and "dev-deferred" not in target["tags"]
        ),
        "WORKSPACE_DEFERRED_TEST_TARGETS": sorted(
            target["label"]
            for target in executable_tests
            if "pr-deferred" in target["tags"]
        ),
        "WORKSPACE_CARGO_TEST_TARGETS": sorted(
            target["label"] for target in executable_tests if "manual" in target["tags"]
        ),
        "WORKSPACE_TEST_TARGETS": sorted(
            target["label"] for target in executable_tests
        ),
    }
    batches = {
        item["test_batch"]["label"]: item["test_batch"]["members"]
        for item in inventory
        if item["test_batch"]["label"]
    }
    batched_members = {member for members in batches.values() for member in members}
    groups["WORKSPACE_TEST_SUITE_LABELS"] = sorted(
        set(groups["WORKSPACE_BAZEL_TEST_TARGETS"]) - batched_members | set(batches)
    )
    groups["WORKSPACE_DEV_SUITE_LABELS"] = sorted(
        set(groups["WORKSPACE_DEV_TEST_TARGETS"]) - batched_members | set(batches)
    )
    # The long tail of `//:workspace_tests`, run on a second CI runner so the
    # partition's wall clock is max(legs), not sum. Two measured tails: the
    # `//examples/` leaves, which sit at the end of the serial compile chain
    # (a core-touching run ends in the agent-workbench unit-test compile), and
    # the `dev-deferred` labels, which are already the tagged slow tests.
    tail_members = {
        target["label"]
        for target in executable_tests
        if "dev-deferred" in target["tags"]
    }
    groups["WORKSPACE_TAIL_SUITE_LABELS"] = sorted(
        label
        for label in groups["WORKSPACE_TEST_SUITE_LABELS"]
        if label.startswith("//examples/") or label in tail_members
    )
    bzl = [GENERATED_HEADER]
    for name, values in groups.items():
        bzl.append(f"{name} = {string_list(values, indent=4)}\n\n")
    bzl.append("WORKSPACE_TEST_BATCHES = {\n")
    for label in sorted(batches):
        bzl.append(
            f"    {quote(label)}: {string_list(batches[label], indent=8)},\n"
        )
    bzl.append("}\n\n")
    outputs[ROOT / "tools/bazel/workspace_targets.bzl"] = "".join(bzl).rstrip() + "\n"
    feature_chunks, feature_bzl, feature_units = feature_lane_outputs(metadata)
    for package in inventory:
        chunk = feature_chunks.get(package["package"])
        if not chunk:
            continue
        macros = sorted(
            {
                line.split("(")[0]
                for line in chunk.splitlines()
                if line.startswith("lash_rust_feature_")
            }
        )
        header = (
            "\n# Feature-lane variants. One target per distinct "
            "`(package, resolved features,\n"
            "# Cargo target kind)` unit of scripts/feature-coverage.toml; see\n"
            "# tools/bazel/feature_variants.py.\n"
            "load(\n"
            "    \"//tools/bazel:lash_rust.bzl\",\n"
            + "".join(f"    {quote(macro)},\n" for macro in macros)
            + ")\n\n"
        )
        manifest = ROOT / package["manifest"]
        outputs[manifest.parent / "BUILD.bazel"] += header + chunk.rstrip("\n") + "\n"
    outputs[ROOT / "tools/bazel/feature_lanes.bzl"] = feature_bzl
    inventory_payload["feature_lane_units"] = sorted(
        feature_units, key=lambda unit: (unit["label"], unit["kind"])
    )
    outputs[ROOT / "tools/bazel/target-inventory.json"] = (
        json.dumps(inventory_payload, indent=2, sort_keys=True) + "\n"
    )
    def cargo_owned_terms(*exclude_tags: str) -> list[str]:
        excluded = set(exclude_tags)
