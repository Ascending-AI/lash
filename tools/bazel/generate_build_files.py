def validate_source_ownership(metadata: dict) -> None:
    members = set(metadata["workspace_members"])
    packages = {
        relative(package["manifest_path"]).removesuffix("/Cargo.toml"): package
        for package in metadata["packages"]
        if package["id"] in members
    }
    for directory, policy in SOURCE_OWNERSHIP.items():
        if directory not in packages:
            raise ValueError(f"source ownership names unknown package {directory}")
        if policy.keys() - {"tests", "library_test_sources", "unit_test_sources", "compile_data", "test_data"}:
            raise ValueError(f"unknown source ownership keys for {directory}")
        package = packages[directory]
        tests = {
            target["name"]: target
            for target in package["targets"]
            if "test" in target["kind"]
        }
        for name, patterns in policy.get("tests", {}).items():
            if name not in tests:
                raise ValueError(f"source ownership names unknown test {directory}:{name}")
            crate_root = relative(tests[name]["src_path"]).removeprefix(directory + "/")
            if crate_root not in patterns:
                raise ValueError(f"source ownership omits root {directory}/{crate_root}")
        unit_patterns = policy.get("unit_test_sources", [])
        if unit_patterns:
            library = next(
                (target for target in package["targets"] if "lib" in target["kind"]),
                None,
            )
            if library is None or not library.get("test", False):
                raise ValueError(f"unit-test ownership names no testable library: {directory}")
            root = relative(library["src_path"]).removeprefix(directory + "/")
            if root not in unit_patterns:
                raise ValueError(f"unit-test ownership omits root {directory}/{root}")
        groups = [
            *policy.get("tests", {}).values(),
            policy.get("library_test_sources", []),
            unit_patterns,
        ]
        for patterns in groups:
            for pattern in patterns:
                if (
                    not pattern.endswith(".rs")
                    or pattern.startswith("/")
                    or ".." in pathlib.PurePosixPath(pattern).parts
                ):
                    raise ValueError(f"invalid Rust source pattern {directory}/{pattern}")
                if not any((ROOT / directory).glob(pattern)):
                    raise ValueError(f"source pattern matches nothing: {directory}/{pattern}")
        if "compile_data" in policy:
            if not any(
                kind in ("lib", "bin", "example")
                for target in package["targets"]
                for kind in target["kind"]
            ):
                raise ValueError(f"compile data names no library or binary: {directory}")
            patterns = policy["compile_data"]
            if not isinstance(patterns, list):
                raise ValueError(f"compile data must be a list: {directory}")
            for pattern in patterns:
                validate_data_pattern(directory, pattern, rust_allowed=False)
        test_data = policy.get("test_data", {})
        if not isinstance(test_data, dict):
            raise ValueError(f"test data must map test targets to patterns: {directory}")
        for name, patterns in test_data.items():
            if name not in tests:
                raise ValueError(f"test data names unknown test {directory}:{name}")
            if not isinstance(patterns, list) or not patterns:
                raise ValueError(f"test data must be a non-empty list: {directory}:{name}")
            for pattern in patterns:
                validate_data_pattern(directory, pattern, rust_allowed=True)
        for source in policy.get("library_test_sources", []):
            if "*" in source or not (ROOT / directory / source).is_file():
                raise ValueError(f"test-only source must name a file: {directory}/{source}")


def validate_data_pattern(directory: str, pattern: object, rust_allowed: bool) -> None:
    if (
        not isinstance(pattern, str)
        or pattern.startswith("/")
        or ".." in pathlib.PurePosixPath(pattern).parts
    ):
        raise ValueError(f"invalid data pattern {directory}/{pattern}")
    matches = [path for path in (ROOT / directory).glob(pattern) if path.is_file()]
    if not matches:
        raise ValueError(f"data pattern matches nothing: {directory}/{pattern}")
    if not rust_allowed and any(path.suffix == ".rs" for path in matches):
        raise ValueError(f"compile data pattern must match non-Rust files: {directory}/{pattern}")


def cargo_metadata() -> dict:
    metadata_env = os.environ.copy()
    for variable in (
        "RUSTC_WRAPPER",
        "RUSTC_WORKSPACE_WRAPPER",
        "CARGO_BUILD_RUSTC_WRAPPER",
        "CARGO_BUILD_RUSTC_WORKSPACE_WRAPPER",
    ):
        metadata_env[variable] = ""
    result = subprocess.run(
        [os.environ.get("KILN_REAL_CARGO", "cargo"), "metadata", "--locked", "--format-version", "1"],
        cwd=ROOT,
        env=metadata_env,
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(result.stdout)


def package_features(metadata: dict) -> dict[str, list[str]]:
    nodes = {node["id"]: sorted(node["features"]) for node in metadata["resolve"]["nodes"]}
    return {package["id"]: nodes.get(package["id"], []) for package in metadata["packages"]}


def relative(path: str) -> str:
    return pathlib.Path(path).resolve().relative_to(ROOT).as_posix()


def label_name(target: dict, primary: bool) -> str:
    kind = target["kind"][0]
    if primary:
        return pathlib.Path(target["src_path"]).resolve().parents[1].name
    suffix = {
        "bin": "bin",
        "example": "example",
        "test": "test",
        "bench": "bench",
    }[kind]
    return f"{target['name']}__{suffix}"


def cargo_bin_env(source: pathlib.Path, labels: dict[str, str]) -> tuple[dict[str, str], list[str]]:
    text = source.read_text()
    env = {}
    deps = []
    for cargo_name, label in labels.items():
        key = f"CARGO_BIN_EXE_{cargo_name}"
        if key in text:
            env[key] = f"$(rootpath :{label})"
            deps.append(f":{label}")
    return env, deps


POLICY_KINDS = {"lib", "unit-test", "bin", "bin-unit-test", "test", "example", "bench"}
POLICY_RULE_KEYS = {
    "packages", "kinds", "targets", "tags", "reason", "compile_data", "data",
    "env", "serial", "args", "bin_env", "shards", "timeout",
}


@dataclass
class TargetPolicy:
    """Everything `tools/bazel/package-policy.toml` says about one label."""

    tags: list[str] = field(default_factory=list)
    reasons: list[str] = field(default_factory=list)
    compile_data: list[str] = field(default_factory=list)
    data: list[str] = field(default_factory=list)
    env: dict[str, str] = field(default_factory=dict)
    args: list[str] = field(default_factory=list)
    shards: int = 0
    timeout: str | None = None


def policy_rule_selects(rule: dict, package_name: str, kind: str, target_name: str) -> bool:
    return (
        package_name in rule["packages"]
        and ("kinds" not in rule or kind in rule["kinds"])
        and (
            "targets" not in rule
            or any(fnmatch.fnmatchcase(target_name, pattern) for pattern in rule["targets"])
        )
    )


def target_policy(
    package_name: str, kind: str, target_name: str, targets: list[dict] | None = None
) -> TargetPolicy:
    """Fold every policy rule that selects one label, in file order.

    `targets` resolves `bin_env` to the named binary's label; a caller that
    reads no `bin_env` may omit it.
    """
    policy = TargetPolicy()
    for rule in PACKAGE_POLICY.get("rule", []):
        if not policy_rule_selects(rule, package_name, kind, target_name):
            continue
        policy.tags.extend(rule.get("tags", []))
        if "reason" in rule:
            policy.reasons.append(rule["reason"])
        policy.compile_data.extend(rule.get("compile_data", []))
        policy.data.extend(rule.get("data", []))
        policy.env.update(rule.get("env", {}))
        if rule.get("serial"):
            policy.env["RUST_TEST_THREADS"] = "1"
        policy.args.extend(rule.get("args", []))
        for variable, binary in rule.get("bin_env", {}).items():
            if targets is None:
                continue
            helper = next(candidate for candidate in targets if candidate["name"] == binary)
            label = f":{label_name(helper, False)}"
            policy.env[variable] = f"$(rootpath {label})"
            policy.data.append(label)
        policy.shards = rule.get("shards", policy.shards)
        policy.timeout = rule.get("timeout", policy.timeout)
    return policy


def validate_package_policy(metadata: dict) -> None:
    """Refuse a policy rule that names nothing, so a rename cannot orphan it."""
    members = {
        package["name"]: package
        for package in metadata["packages"]
        if package["id"] in set(metadata["workspace_members"])
    }
    for index, rule in enumerate(PACKAGE_POLICY.get("rule", [])):
        where = f"package-policy.toml rule {index + 1}"
        if rule.keys() - POLICY_RULE_KEYS:
            raise ValueError(f"{where}: unknown keys {sorted(rule.keys() - POLICY_RULE_KEYS)}")
        unknown = [name for name in rule.get("packages", []) if name not in members]
        if not rule.get("packages") or unknown:
            raise ValueError(f"{where}: unknown or missing packages {unknown}")
        if set(rule.get("kinds", [])) - POLICY_KINDS:
            raise ValueError(f"{where}: unknown kinds {sorted(set(rule['kinds']) - POLICY_KINDS)}")
        names = {
            target["name"]
            for name in rule["packages"]
            for target in members[name]["targets"]
        }
        for pattern in rule.get("targets", []):
            if not fnmatch.filter(sorted(names), pattern):
                raise ValueError(f"{where}: target pattern {pattern!r} matches nothing")
        for binary in rule.get("bin_env", {}).values():
            if binary not in names:
                raise ValueError(f"{where}: bin_env names unknown binary {binary!r}")
    test_runs = PACKAGE_POLICY.get("test_runs", {})
    unknown_floor = [
        name
        for name in test_runs.get("contention_floor", {}).get("packages", [])
        if name not in members
    ]
    if unknown_floor:
        raise ValueError(f"package-policy.toml [test_runs.contention_floor] names {unknown_floor}")
    for service, names in PACKAGE_POLICY.get("service_packages", {}).items():
        if not names or any(name not in members for name in names):
            raise ValueError(f"package-policy.toml [service_packages] {service} names {names}")
    for section in ("feature_compile_data", "filegroups", "ui_fixtures"):
        for name in PACKAGE_POLICY.get(section, {}):
            if name not in members:
                raise ValueError(f"package-policy.toml [{section}] names unknown package {name}")


def cargo_test_policy(
    package_name: str, kind: str, target_name: str
) -> tuple[list[str], str | None]:
    """Classify one executable test label as partition-owned or Cargo-owned.

    `manual` keeps a label out of `//:workspace_tests` and out of `bazel test
    //...`. It is reserved for labels the cacheable partition genuinely cannot
    execute as proof: a live service, a nested Cargo invocation, a Cargo-relative
    asset tree, or a toolchain the Bazel job does not install. Service-gated
    labels are still *built* by Bazel; the PostgreSQL and MinIO jobs execute
    them with `--nocache_test_results` so a cached result can never stand in for
    a run against a real service, and so an unconfigured service is never proof.
    """
    policy = target_policy(package_name, kind, target_name)
    reason = "; ".join(policy.reasons) if policy.reasons else None
    return sorted(set(policy.tags)), reason


def bazel_test_shard_count(package_name: str, kind: str, target_name: str) -> int:
    """How many parallel Bazel test actions one libtest binary is split into.

    A libtest binary is a single test action, so a crate that packs hundreds of
    cases into one binary sets the partition's critical path no matter how many
    executor slots are free. `rust_test`'s sharding wrapper lists the binary,
    assigns each case to a shard by a stable name hash and runs only that
    subset, so the shards execute disjoint subsets whose union is every case the
    unsharded binary runs. Sharding is opt-in: each shard pays its own `--list`
    execution and runfiles tree, so only a binary whose wall time dominates the
    job earns one.
    """
    return target_policy(package_name, kind, target_name).shards


def nextest_filter_term(package_name: str, target: dict) -> str:
    """Select exactly one Cargo test binary in nextest's filter language."""
    kind = target["kind"]
    if kind == "unit-test":
        target_filter = "kind(lib)"
    elif kind == "bin-unit-test":
        target_filter = f"kind(bin) & binary({target['cargo']})"
    elif kind == "test":
        target_filter = f"kind(test) & binary({target['cargo']})"
    else:
        raise ValueError(f"unsupported nextest target kind: {kind}")
    return f"(package({package_name}) & {target_filter})"


def library_compile_data(package_name: str, library_name: str) -> list[str]:
    """Sandbox inputs the library compile of one package needs."""
    return target_policy(package_name, "lib", library_name).compile_data


def unit_test_compile_data(package_name: str, library_name: str) -> list[str]:
    """Sandbox inputs the unit-test compile of one package needs."""
    return target_policy(package_name, "unit-test", library_name).compile_data


def target_support(
    package: dict,
    targets: list[dict],
    target: dict,
    kind: str,
) -> tuple[list[str], list[str], dict[str, str], list[str]]:
    """The per-target sandbox inputs, runtime inputs, test env and skips.

    The ordinary target loop and the feature-lane variants of the same Cargo
    target both read it, so a variant carries exactly the same support data;
    a variant that dropped one of these would pass by seeing nothing.
    """
    # A binary's unit test compiles the binary's sources, so it takes the
    # binary's support; its own run data is the `bin-unit-test` policy.
    kind = "bin" if kind == "bin-unit-test" else kind
    policy = target_policy(package["name"], kind, target["name"], targets)
    return policy.compile_data, policy.data, policy.env, policy.args


def filegroups(package_name: str) -> str:
    """Package files other packages' targets name as inputs."""
    chunks = []
    for name, spec in PACKAGE_POLICY.get("filegroups", {}).get(package_name, {}).items():
        if "glob" in spec:
            srcs = f"glob({string_list(spec['glob'], indent=8)})"
        else:
            srcs = string_list(spec["srcs"])
        chunks.append(
            "filegroup(\n"
            f"    name = {quote(name)},\n"
            f"    srcs = {srcs},\n"
            ")\n\n"
        )
    return "".join(chunks)


def render_package(package: dict, features: list[str]) -> tuple[str, dict]:
    manifest = relative(package["manifest_path"])
    package_dir = pathlib.PurePosixPath(manifest).parent.as_posix()
    version = package["version"]
    declared_features = sorted(package["features"])
    targets = [target for target in package["targets"] if "custom-build" not in target["kind"]]
    resolved_feature_set = set(features)

