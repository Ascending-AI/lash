# Measured per-target remote requests, keyed `<rustc --crate-name>/<kind>`. The
# repository default in `.bazelrc` is the small action; everything heavier says
# so here, and the sizes are written literally into the generated BUILD files so
# the request is visible in the diff rather than resolved at analysis time.
# Rebuilt by `tools/bazel/action_sizes_from_log.py`.
ACTION_SIZES_PATH = ROOT / "tools/bazel/action-sizes.json"
DEFAULT_MEMORY_KB = 2097152
DEFAULT_CPU_COUNT = 1
# A test action is a whole libtest binary, not one rustc invocation: it runs a
# tokio runtime, a store, and by default one test thread per core, so the
# measured compile-time CPU of the crate says nothing about what running the
# suite needs. At the repository default of one core the runtime's own threads
# and the harness's contend for that single core, and time-sensitive cases fail
# or time out rather than run slowly -- CI run 34950810111 lost
# `//crates/lash-perf:lash-perf__unit_test` on a phase assertion and timed out
# `//crates/lash-sim:stack_policy__test` that way. Test kinds therefore floor at
# four cores; libs, bins and build scripts stay exactly as measured.
TEST_CPU_FLOOR = 4
TEST_SIZE_KINDS = ("test",)
# Sized targets retain the four-core / 4 GiB safety floor established for the
# test partition and measured compile requests. These are explicit target
# requirements, independent of the small-action defaults used by local and CI
# invocations. An unsized target inherits that invocation's defaults; once a
# target needs either resource above the default, emit both safety floors.
SIZED_CPU_FLOOR = 4
SIZED_MEMORY_FLOOR = 4194304
# A measured average can never exceed the cap the sample ran under, so a
# CPU-bound compile cannot argue its own way up the table:
# `tools/bazel/action_sizes_from_log.py` divides observed CPU seconds by wall
# seconds, and a saturated action reads as "sized correctly". The
# lash-internal-core rlib kept 222 cpu-seconds busy over 128 s wall at a cap of
# two on CI run 35009804570 --- saturated, and the single action that owns the
# critical path of all three Bazel jobs. rustc's codegen phase parallelises
# across codegen units (256 of them in the debug geometry), so the cap is the
# lever, and for the actions on that chain --- the lash-internal-core rlib, the
# facade rlib compiled on top of it, and the test binaries that link them --- it
# is declared here rather than measured. A floor is honoured whether or not the
# key appears in the measured table, so regenerating the table from a log that
# happens not to contain the crate cannot quietly drop it.
CPU_FLOORS = {
    "agent_workbench/bin": 8,
    "agent_workbench/test": 8,
    "lash/lib": 8,
    "lash/test": 8,
    "lash_core/lib": 8,
    "lash_core/test": 8,
    "lash_restate/test": 8,
}
# `//crates/lash-sim:lash-sim__unit_test` packs the whole simulation suite into
