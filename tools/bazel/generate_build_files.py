def cargo_test_policy(
    package_name: str, kind: str, target_name: str
) -> tuple[list[str], str | None]:
    """Classify one executable test label as partition-owned or Cargo-owned.

    `manual` keeps a label out of `//:workspace_tests` and out of `bazel test
    //...`. It is reserved for labels the cacheable partition genuinely cannot
    execute as proof: a live service, a nested Cargo invocation, a Cargo-relative
    asset tree, or a toolchain the Bazel job does not install. Service-gated
    labels are still *built* by Bazel; the PostgreSQL and MinIO jobs execute
    them with `--nocache_test_results` so a cached result can never stand in for
    a run against a real service, and so an unconfigured service is never proof.
    """
    tags = []
    reasons = []
    if package_name in ("lash-internal-postgres-store", "lash-internal-s3-store"):
        tags.extend(["manual", "cargo-service-gate"])
        reasons.append(
            "proves nothing without a live PostgreSQL or MinIO; the service jobs"
            " execute this label uncached against a real service"
        )
    if package_name == "lash-runtime" and target_name == "ui":
        tags.extend(["manual", "cargo-trybuild"])
        reasons.append("uses trybuild and its Cargo-managed compiler fixture cache")
    if package_name == "workflow-graph-roundtrip" and kind == "test":
        tags.extend(["manual", "cargo-frontend-assets"])
        reasons.append("uses the Cargo-owned generated frontend asset workflow")
    if package_name == "lash-sim" and target_name.startswith("cross_backend"):
        tags.extend(["manual", "cargo-service-gate"])
        reasons.append(
            "proves nothing without a live PostgreSQL or MinIO; the service jobs"
            " execute this label uncached against a real service"
        )
    if package_name == "lash-sim" and kind == "unit-test":
        tags.append("dev-deferred")
        reasons.append(
            "the generated-profile, minimizer and replay-artifact cases run"
            " 109--213 s; too slow for the developer loop, still in the PR"
            " Bazel partition"
        )
    if package_name == "lash-internal-typescript" and kind == "test":
        # Partition-owned, but not remotely executable: the no-abort guarantee
        # forks a dozen children that each parse deliberately deep sources
        # right up to the stack bound, and their combined footprint exceeds any
        # single-action memory budget the pool grants -- re-measured against
        # the raised floor, `the_abort_corpus_survives_without_the_preflight`
        # and `fuzzed_sources_survive_without_the_preflight` still die of
        # `signal: 9 (SIGKILL)`. The same label passes locally in 43 s. Pin the
        # placement rather than soften what the test proves.
        tags.extend(["no-remote-exec", "dev-deferred"])
        reasons.append(
            "the no-abort stress binary runs 43 s; too slow for the developer"
            " loop, still in the PR Bazel partition"
        )
    if package_name == "lash-regress" and target_name == "unicodesets":
        tags.append("pr-deferred")
        reasons.append(
            "RGI Unicode suites are too slow for the PR Bazel partition; they"
            " run on lash-regress diffs and on trunk"
        )
    reason = "; ".join(reasons) if reasons else None
    return sorted(set(tags)), reason


def bazel_test_shard_count(package_name: str, kind: str, target_name: str) -> int:
    """How many parallel Bazel test actions one libtest binary is split into.

    A libtest binary is a single test action, so a crate that packs hundreds of
    cases into one binary sets the partition's critical path no matter how many
    executor slots are free. `rust_test`'s sharding wrapper lists the binary,
    assigns each case to a shard by a stable name hash and runs only that
    subset, so the shards execute disjoint subsets whose union is every case the
    unsharded binary runs. Sharding is opt-in: each shard pays its own `--list`
    execution and runfiles tree, so only a binary whose wall time dominates the
    job earns one.
    """
    if package_name == "lash-sim" and kind == "unit-test":
        return LASH_SIM_UNIT_TEST_SHARDS
    return 0


def nextest_filter_term(package_name: str, target: dict) -> str:
    """Select exactly one Cargo test binary in nextest's filter language."""
    kind = target["kind"]
    if kind == "unit-test":
        target_filter = "kind(lib)"
    elif kind == "bin-unit-test":
        target_filter = f"kind(bin) & binary({target['cargo']})"
    elif kind == "test":
        target_filter = f"kind(test) & binary({target['cargo']})"
    else:
        raise ValueError(f"unsupported nextest target kind: {kind}")
    return f"(package({package_name}) & {target_filter})"


