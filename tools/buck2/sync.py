"""Synchronize Cargo's locked Lash graph into checked-in Buck2 files.

The source Cargo manifests and lockfile remain authoritative.  This command
derives a standalone external-crate manifest for Reindeer, the generated
first-party BUCK files, dependency tables, sizing tables, and the caller
inventory.  ``--check`` computes all expected text without modifying the
checkout.
"""

