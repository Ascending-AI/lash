    source_text = synthetic_source()
    outputs: dict[pathlib.Path, str] = {
        SYNTHETIC / "Cargo.toml": manifest_text,
        SYNTHETIC / "src/lib.rs": source_text,
    }
    if args.check:
        lock_path = SYNTHETIC / "Cargo.lock"
        if not lock_path.is_file():
            return write_or_check({**outputs, lock_path: ""}, True)
        outputs[lock_path] = lock_path.read_text()
    else:
        outputs[SYNTHETIC / "Cargo.lock"] = generate_lock(manifest_text, source_text)
        write_or_check(outputs, False)

    derived = metadata(SYNTHETIC / "Cargo.toml")
    validate_synthetic(canonical, derived)
    validate_buildscript_fixups(derived)
    third_party_buck = inject_buildscript_metadata(
        enable_buildscript_link_directives(buckify_stdout(), buildscript_link_opt_outs()),
        derived,
    )
    third_party_buck, git_sources = vendored_git_rules(third_party_buck, derived)
    outputs[SYNTHETIC / "rust/git-sources.json"] = json.dumps(git_sources, indent=2) + "\n"
    targets = parse_third_party_targets(third_party_buck)
    outputs[ROOT / "third-party/rust/BUCK"] = third_party_buck
    outputs[BUCK2 / "deps.bzl"] = deps_bzl(dependency_table(canonical, targets))
    outputs[BUCK2 / "profile.bzl"] = profile_bzl(canonical)
    outputs.update(model_outputs(canonical, targets))
    failures = generate_model.reconcile_lane_units(
        canonical, json.loads(outputs[BUCK2 / "target-inventory.json"])["feature_lane_units"]
    )
    if failures:
        for failure in failures:
            print(f"feature-lane graph differs from Cargo: {failure}", file=sys.stderr)
        return 1
    result = write_or_check(outputs, args.check)
    if result == 0:
        if not args.check:
            subprocess.run([sys.executable, str(BUCK2 / "bootstrap_vendor.py")], cwd=ROOT, check=True)
            materialize_git_sources()
        write_receipt(outputs)
    return result


