def profile_bzl(canonical: dict) -> str:
    manifest = tomllib.loads((ROOT / "Cargo.toml").read_text())
    overrides = manifest.get("profile", {}).get("dev", {}).get("package", {})
    members = set(canonical["workspace_members"])
    member_names = {
        package["name"] for package in canonical["packages"] if package["id"] in members
    }
    # Cargo's host-side proc-macro support crates already compile in the exec
    # configuration. Preserve the existing graph policy by leaving them on the
    # ordinary execution profile rather than applying target-package overrides.
    host_only = {"proc-macro2", "quote", "syn"}
    first_party: dict[str, int] = {}
    third_party: dict[str, int] = {}
    for name, values in sorted(overrides.items()):
        if name == "*":
            continue
        if set(values) != {"opt-level"}:
            raise SystemExit(f"unsupported dev profile keys for {name}: {sorted(values)}")
        if name in member_names:
            first_party[name] = int(values["opt-level"])
        elif name not in host_only:
            third_party[name] = int(values["opt-level"])
    return (
        GENERATED_HEADER
        + "FIRST_PARTY_OPT_LEVELS = "
        + json.dumps(first_party, indent=4, sort_keys=True)
        + "\n\nTHIRD_PARTY_OPT_LEVELS = "
        + json.dumps(third_party, indent=4, sort_keys=True)
        + "\n"
    )


def inventory_payload(model_payload: dict, workspace_bzl: str, feature_bzl: str) -> dict:
    def list_value(name: str, text: str) -> list[str]:
        match = re.search(rf"{name} = (\[.*?\])\n", text, re.S)
        if not match:
            raise SystemExit(f"generated table lacks {name}")
        return ast.literal_eval(match.group(1))

    lanes_match = re.search(r"FEATURE_LANES = (\{.*\})\n$", feature_bzl, re.S)
    if not lanes_match:
        raise SystemExit("generated table lacks FEATURE_LANES")
    floors_match = re.search(
        r"FEATURE_LANE_TEST_FLOORS = (\{.*?\})\n\nFEATURE_LANES", feature_bzl, re.S
    )
    if not floors_match:
        raise SystemExit("generated table lacks FEATURE_LANE_TEST_FLOORS")
    args_match = re.search(
        r"FEATURE_LANE_TEST_ARGS = (\{.*?\})\n\nFEATURE_LANE_TEST_FLOORS", feature_bzl, re.S
    )
    if not args_match:
        raise SystemExit("generated table lacks FEATURE_LANE_TEST_ARGS")

    result = dict(model_payload)
    result.update(
        {
            "workspace_compile_targets": list_value("WORKSPACE_COMPILE_TARGETS", workspace_bzl),
            "workspace_test_targets": list_value("WORKSPACE_TEST_TARGETS", workspace_bzl),
            "workspace_dev_test_targets": list_value("WORKSPACE_DEV_TEST_TARGETS", workspace_bzl),
            "workspace_deferred_test_targets": list_value("WORKSPACE_DEFERRED_TEST_TARGETS", workspace_bzl),
            "workspace_test_suite_labels": list_value("WORKSPACE_TEST_SUITE_LABELS", workspace_bzl),
            "workspace_dev_suite_labels": list_value("WORKSPACE_DEV_SUITE_LABELS", workspace_bzl),
            "workspace_tail_suite_labels": list_value("WORKSPACE_TAIL_SUITE_LABELS", workspace_bzl),
            "workspace_test_batches": {
                package["test_batch"]["label"]: package["test_batch"]["members"]
                for package in model_payload["packages"]
                if package["test_batch"]["label"]
            },
            "workspace_doc_targets": list_value("WORKSPACE_DOC_TARGETS", workspace_bzl),
            "workspace_clippy_targets": list_value("WORKSPACE_CLIPPY_TARGETS", workspace_bzl),
            "workspace_rust_source_targets": list_value(
                "WORKSPACE_RUST_SOURCE_TARGETS", workspace_bzl
            ),
            "feature_lane_compile_targets": list_value("FEATURE_LANE_COMPILE_TARGETS", feature_bzl),
            "feature_lane_test_targets": list_value("FEATURE_LANE_TEST_TARGETS", feature_bzl),
            "feature_lanes": ast.literal_eval(lanes_match.group(1)),
            "feature_lane_test_args": ast.literal_eval(args_match.group(1)),
            "feature_lane_test_floors": ast.literal_eval(floors_match.group(1)),
            "service_test_targets": {},
        }
    )
    timeout_names = {None: 300, "short": 60, "moderate": 300, "long": 900, "eternal": 3600}
    timeouts: dict[str, int] = {}
    ordinary: list[tuple[str, int]] = []
    for package in result["packages"]:
        for target in package["targets"]:
            label = target.get("label")
            if label is None or target["kind"] not in {"unit-test", "bin-unit-test", "test"}:
                continue
            policy = generate_model.target_policy(
                package["package"], target["kind"], target["cargo"]
            )
            seconds = timeout_names[policy.timeout]
            timeouts[label] = seconds
            ordinary.append((label, seconds))
        batch = package["test_batch"]["label"]
        if batch:
            timeouts[batch] = 300
    for unit in result["feature_lane_units"]:
        if unit["kind"] not in {"unit-test", "bin-unit-test", "test"}:
            continue
        base = unit["label"].split("__fv_", 1)[0]
        timeouts[unit["label"]] = next(
            (seconds for label, seconds in ordinary if label == base), 300
        )
    result["test_timeout_seconds"] = dict(sorted(timeouts.items()))
    result["workspace_core_suite_labels"] = sorted(
        set(result["workspace_test_suite_labels"]) - set(result["workspace_tail_suite_labels"])
    )

    def output_label(label: str, kind: str) -> str:
        return label + "[static]" if kind == "lib" else label

    def clippy_label(label: str) -> str:
        # The Clippy twin lash_rust.bzl declares beside every Rust target: the
        # same rule on its own execution platform, sized for Clippy.
        return label + "__clippy[clippy.txt]"

    kinds: dict[str, str] = {}
    for package in result["packages"]:
        for target in package["targets"]:
            if target.get("label"):
                target["build_label"] = output_label(target["label"], target["kind"])
                if target["kind"] == "lib":
                    target["doc_label"] = target["label"] + "[doc]"
                if target["kind"] != "custom-build":
                    target["clippy_label"] = clippy_label(target["label"])
                if target["kind"] != "custom-build":
                    target["check_label"] = target["label"] + "[check]"
                kinds[target["label"]] = target["kind"]
    for unit in result["feature_lane_units"]:
        unit["build_label"] = output_label(unit["label"], unit["kind"])
        if unit["kind"] == "lib":
            unit["doc_label"] = unit["label"] + "[doc]"
        unit["check_label"] = unit["label"] + "[check]"
        unit["clippy_label"] = clippy_label(unit["label"])
        kinds[unit["label"]] = unit["kind"]
    result["workspace_build_targets"] = [
        output_label(label, kinds.get(label, ""))
        for label in result["workspace_compile_targets"]
    ]
    checks = {
        target["label"]: target["check_label"]
        for package in result["packages"]
        for target in package["targets"]
        if "check_label" in target
    }
    result["workspace_check_targets"] = [
        checks[label]
        for label in result["workspace_compile_targets"]
        if label in checks
    ]
    result["feature_lane_build_targets"] = [
        output_label(label, kinds.get(label, ""))
        for label in result["feature_lane_compile_targets"]
    ]
    result["feature_lane_check_targets"] = [
        label + "[check]" for label in result["feature_lane_compile_targets"]
    ]
    result["workspace_clippy_build_targets"] = [
        clippy_label(label) for label in result["workspace_clippy_targets"]
    ]
    return result


