//! A released helper set as the repository keeps it, and what a build makes
//! of the ones it retains (FIG-5799).
//!
//! A release is frozen as data: every function a build of it holds, by
//! identity, with its definition and, for a native implementation, the
//! digest of what the code behind it answers (`probe.rs`). The build checks
//! each definition's identity, holds every body a run may still pin that
//! the build does not define itself, and compares each native digest with
//! the build's own: a native that answers otherwise under the same identity
//! fails the build, since its code is not in its definition and it is
//! stated anew under its next native version (`K-LIB-011`). A sealed
//! release, one that has shipped, fails the build on any other difference;
//! the release the tree is still building records it for its law, which
//! names the generator that freezes it again.
//!
//! The build script includes this file.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use lash_kernel_doc::{FunctionDefinition, FunctionId, FunctionRegistry};
use serde::{Deserialize, Serialize};

use crate::releases::HelperReleaseIndex;

/// The generator that freezes the release the tree builds again.
pub(crate) const FREEZE: &str = "kiln test //crates/lash-vm-worker:lash-vm-worker__unit_test --local-test-execution --no-test-cache --test_arg=--ignored --test_arg=--exact --test_arg=embedding::release_tests::regenerate_helper_release --test_env=LASH_REGENERATE=1 --test_env=BUILD_WORKSPACE_DIRECTORY=$PWD";

/// One released helper set, as `src/generated/` keeps it.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct HelperRelease {
    pub(crate) release: String,
    pub(crate) ordinal: u32,
    /// The release has shipped: what it holds is fixed, and a build that
    /// cannot hold it exactly fails.
    #[serde(default, skip_serializing_if = "is_false")]
    pub(crate) sealed: bool,
    /// The functions a build of the release resolves names against.
    pub(crate) writes: BTreeSet<FunctionId>,
    /// Every function the release holds, each after the functions its body
    /// calls.
    pub(crate) functions: Vec<ReleasedFunction>,
}

/// A function of a released set.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct ReleasedFunction {
    pub(crate) function: FunctionId,
    pub(crate) definition: FunctionDefinition,
    /// The digest of what its native implementation answered when the
    /// release was frozen.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub(crate) fingerprint: Option<String>,
}

fn is_false(value: &bool) -> bool {
    !*value
}

impl HelperRelease {
    /// Reads a release as `src/generated/` keeps it. A body nests as deep as
    /// its definition does.
    pub(crate) fn decode(text: &str) -> Result<Self, String> {
        let mut decoder = serde_json::Deserializer::from_str(text);
        decoder.disable_recursion_limit();
        let release = Self::deserialize(&mut decoder).map_err(|error| error.to_string())?;
        decoder.end().map_err(|error| error.to_string())?;
        Ok(release)
    }

    /// The Rust source `src/generated/` keeps the release in: its JSON, one
    /// function to a line, as a string constant.
    pub(crate) fn source(&self) -> Result<String, String> {
        let mut text = format!(
            "{{\"release\":{},\"ordinal\":{},",
            json(&self.release)?,
            self.ordinal
        );
        if self.sealed {
            text.push_str("\"sealed\":true,");
        }
        let _ = write!(text, "\"writes\":{},\"functions\":[", json(&self.writes)?);
        for (index, function) in self.functions.iter().enumerate() {
            text.push_str(if index == 0 { "\n" } else { ",\n" });
            text.push_str(&json(function)?);
        }
        text.push_str("\n]}\n");
        let mut hashes = String::from("#");
        while text.contains(&format!("\"{hashes}")) {
            hashes.push('#');
        }
        Ok(format!(
            "// @generated by `{FREEZE}`; do not edit.\n\
             //! Helper release {release}: every function a build of it holds (FIG-5799).\n\n\
             pub(crate) const RELEASE: &str = r{hashes}\"{text}\"{hashes};\n",
            release = self.release,
        ))
    }

    /// What the worker keeps of the release.
    pub(crate) fn index(&self) -> HelperReleaseIndex {
        HelperReleaseIndex {
            release: self.release.clone(),
            ordinal: self.ordinal,
            writes: self.writes.clone(),
            functions: self
                .functions
                .iter()
                .map(|function| function.function)
                .collect(),
        }
    }
}

fn json(value: &impl Serialize) -> Result<String, String> {
    serde_json::to_string(value).map_err(|error| error.to_string())
}

/// What a build holds of the releases it retains.
#[derive(Debug, Default)]
pub(crate) struct Kept {
    /// The functions the build holds besides its own, each after the
    /// functions its body calls.
    pub(crate) retained: Vec<FunctionDefinition>,
    /// Where the release the tree is still building and the build part.
    pub(crate) divergence: Vec<String>,
}

/// The functions of `releases` that `registry`, the build's own, does not
/// hold, checked against it: every definition under its identity, every
/// native the release holds implemented here and answering as it did.
///
/// # Errors
///
/// A definition that is not under its identity, and any difference from a
/// sealed release.
pub(crate) fn keep(
    releases: &[HelperRelease],
    registry: &FunctionRegistry,
    fingerprints: &BTreeMap<FunctionId, String>,
) -> Result<Kept, String> {
    let mut kept = Kept::default();
    let mut held: BTreeSet<FunctionId> = registry.iter().map(|(function, _)| *function).collect();
    for release in releases {
        let mut differs = |message: String| {
            let message = format!("helper release {}: {message}", release.release);
            if release.sealed {
                Err(message)
            } else {
                kept.divergence.push(message);
                Ok(())
            }
        };
        let listed: BTreeSet<FunctionId> = release
            .functions
            .iter()
            .map(|function| function.function)
            .collect();
        if let Some(missing) = release.writes.iter().find(|id| !listed.contains(id)) {
            return Err(format!(
                "helper release {} writes {missing}, which it does not hold",
                release.release
            ));
        }
        for released in &release.functions {
            let function = released.function;
            let name = &released.definition.name;
            let identity = released
                .definition
                .identity()
                .map_err(|error| error.to_string())?;
            if identity != function {
                return Err(format!(
                    "helper release {} holds `{name}` as {function}, and its definition is {identity}",
                    release.release
                ));
            }
            if let Some(registered) = registry.get(&function) {
                // A native that answers otherwise under the identity a run
                // pinned would change that run: the build fails, whatever
                // the release (`K-LIB-011`).
                if registered.native.is_some()
                    && released.fingerprint.as_ref() != fingerprints.get(&function)
                {
                    return Err(format!(
                        "helper release {}: native `{name}` ({function}) answers otherwise than when the \
                         release was frozen; a changed native implementation is stated under its next \
                         native version (`native 2`), which is a new function, and the release is frozen \
                         again: {FREEZE}",
                        release.release
                    ));
                }
                continue;
            }
            if held.contains(&function) {
                continue;
            }
            if released.definition.has_native() {
                differs(format!(
                    "native `{name}` ({function}) is not implemented by this build"
                ))?;
                continue;
            }
            let calls = released
                .definition
                .body()
                .map(|body| body.functions.keys().copied().collect::<Vec<_>>())
                .unwrap_or_default();
            if let Some(missing) = calls.iter().find(|called| !held.contains(called)) {
                differs(format!(
                    "`{name}` ({function}) calls {missing}, which this build does not hold"
                ))?;
                continue;
            }
            held.insert(function);
            kept.retained.push(released.definition.clone());
        }
        if !release.sealed {
            let own: BTreeSet<FunctionId> =
                registry.iter().map(|(function, _)| *function).collect();
            let added = own.difference(&release.writes).count();
            let dropped = release.writes.difference(&own).count();
            if added + dropped > 0 {
                differs(format!(
                    "the build's functions are not the ones the release writes \
                     ({added} not in it, {dropped} of it not built); freeze it again: {FREEZE}"
                ))?;
            }
        }
    }
    Ok(kept)
}

/// Release `release`, ordinal `ordinal`, frozen for `registry`, the build's
/// own functions: it writes them, and it still holds every function of
/// `previous`, an earlier freeze of it, whose body this build can run, so
/// a run written against that freeze resumes.
pub(crate) fn freeze(
    release: &str,
    ordinal: u32,
    previous: Option<&HelperRelease>,
    registry: &FunctionRegistry,
    fingerprints: &BTreeMap<FunctionId, String>,
) -> HelperRelease {
    let mut functions = Vec::new();
    let mut listed = BTreeSet::new();
    for (function, _) in registry.iter() {
        list(
            *function,
            registry,
            fingerprints,
            &mut listed,
            &mut functions,
        );
    }
    let writes = listed.clone();
    for released in previous.map_or(&[][..], |previous| &previous.functions) {
        let runnable = !released.definition.has_native()
            && released
                .definition
                .body()
                .is_some_and(|body| body.functions.keys().all(|called| listed.contains(called)));
        if runnable && listed.insert(released.function) {
            functions.push(ReleasedFunction {
                fingerprint: None,
                ..released.clone()
            });
        }
    }
    HelperRelease {
        release: release.to_owned(),
        ordinal,
        sealed: false,
        writes,
        functions,
    }
}

/// Lists `function` after every function its body calls.
fn list(
    function: FunctionId,
    registry: &FunctionRegistry,
    fingerprints: &BTreeMap<FunctionId, String>,
    listed: &mut BTreeSet<FunctionId>,
    functions: &mut Vec<ReleasedFunction>,
) {
    if listed.contains(&function) {
        return;
    }
    let Some(registered) = registry.get(&function) else {
        return;
    };
    if let Some(body) = registered.definition.body() {
        for called in body.functions.keys() {
            list(*called, registry, fingerprints, listed, functions);
        }
    }
    listed.insert(function);
    functions.push(ReleasedFunction {
        function,
        definition: FunctionDefinition::clone(&registered.definition),
        fingerprint: fingerprints.get(&function).cloned(),
    });
}
