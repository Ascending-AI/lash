var global_res = 0;
function int_to_string(n)
{
    var s, r, j;
    r = 0;
    for(j = 0; j < n; j++) {
        s = (j % 10) + '';
        s = (j % 100) + '';
        s = (j) + '';
    }
    global_res = s;
    return n * 3;
}
function benchmark(n) { int_to_string(n); return global_res.length; }
