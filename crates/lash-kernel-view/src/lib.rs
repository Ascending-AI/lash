/// Whose code or which outside party an action reaches.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum ActionRole {
    /// A `perform`: a request the host answers, such as a tool call. Each
    /// run of it is one effect occurrence, named by its `EffectId`.
    Effect,
    /// A `sleep`: a timed wait. Each run of it is an effect occurrence too,
    /// which no host answers.
    Wait,
    /// A call or `spawn` of the document's own code: a declared function, or
    /// the closure or function reference a variable holds.
    SubWorkflow,
    /// A call or `spawn` of a library function, or an `await` through its
    /// dialect's policy: the dialect's or the kernel's code. `applies`
    /// names a closure of the document it runs.
    Library,
    /// A `join`, `join_many`, `cancel` or `yield`: coordination among the
    /// run's tasks.
    Task,
}

/// What an action does.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum SiteKind {
    Call,
    Perform,
    Sleep,
    Join,
    JoinMany,
    Yield,
    Spawn,
    Cancel,
    /// An `await`: a call of its dialect's await policy.
    Await,
}

impl std::fmt::Display for SiteKind {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::Call => "call",
            Self::Perform => "perform",
            Self::Sleep => "sleep",
            Self::Join => "join",
            Self::JoinMany => "join_many",
            Self::Yield => "yield",
            Self::Spawn => "spawn",
            Self::Cancel => "cancel",
            Self::Await => "await",
        })
    }
}

/// Why a graph has no view of an entry.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum ViewError {
    #[error("the graph has no unit {unit:?}")]
    NoSuchUnit { unit: Unit },
    #[error("the document holds no declaration of library function {function}")]
    MissingFunction { function: FunctionId },
    /// The graph was derived from another document.
    #[error("the graph does not describe the document at {site:?}")]
    Mismatch { site: Site },
}

/// The view of `document` at the entry it is entered at, read from the
/// graph the checker derived from it and the library declarations it linked
/// against, with display and membership facts from the caller's selected
/// package set. No engine or native code is needed.
///
/// # Errors
///
/// The holder's graph or declarations do not describe its document.
pub fn derive(
    document: &WorkflowDocument,
    packages: &PackageView<'_>,
) -> Result<WorkflowView, ViewError> {
    derive_callable(document, &document.entry_unit(), packages)
}

/// Open a declared callable without publishing it as an entry or inlining it
/// into its caller. Library implementations are outside the document view.
///
/// # Errors
///
/// The checked document has no such unit, or its graph/declarations mismatch.
pub fn derive_callable(
    document: &WorkflowDocument,
    entry: &Unit,
    packages: &PackageView<'_>,
) -> Result<WorkflowView, ViewError> {
    let graph = document.graph();
    let functions = document.declarations();
    let document = document.document();
    let unit = graph.unit(entry).ok_or_else(|| ViewError::NoSuchUnit {
        unit: entry.clone(),
    })?;
    let body = match entry {
        Unit::Main => Node::Block(&document.main),
        Unit::Function(name) => match document.functions.get(name) {
            Some(function) => Node::Block(&function.body),
            None => return Err(mismatch(graph.node(unit.body))),
        },
        Unit::Library(_) => return Err(mismatch(graph.node(unit.body))),
    };
    let expected = match entry {
        Unit::Function(name) => document
            .entries
            .get(name)
            .map(|entry| entry.signature.result.clone()),
        Unit::Main | Unit::Library(_) => None,
    };
    let mut walk = Walk {
        packages,
        ordinals: document.site_ordinals(),
        document,
        graph,
        functions,
        entry: Callable {
            site: Site::new(entry.clone(), Vec::new()),
            expected: expected.unwrap_or(Type::Any),
        },
        view: WorkflowView {
            document: document.identity(),
            entry: EntryView {
                name: None,
                params: Vec::new(),
                result: Type::Any,
                result_facet: Type::Any,
            },
            nodes: Vec::new(),
            callables: Vec::new(),
            flow: Vec::new(),
            canonical_source: String::new(),
            readable: ReadableLens::Unrequested,
            statements: Vec::new(),
            scopes: Vec::new(),
            dataflow: Dataflow {
                parameters: unit.params.iter().map(|id| id.index()).collect(),
                ..Dataflow::default()
            },
            execution_sites: graph.execution_sites().iter().map(execution_site).collect(),
        },
        uses: BTreeMap::new(),
        links: applies::Links::new(),
    };
    let at = Context {
        block: walk.entry.site.clone(),
        statement: None,
        depth: 0,
        callable: walk.entry.clone(),
        assigns: None,
        opens: Some(ScopeKind::Entry),
    };
    walk.node(unit.body, body, &at)?;
    let Walk {
        mut view, mut uses, ..
    } = walk;
    let producers = produced::Producers::new(graph, functions, &view.dataflow.actions, packages);
    let bindings = graph
        .bindings()
        .iter()
        .filter(|binding| graph.node(binding.declared_at).site.unit == *entry)
        .map(|binding| {
            let declaration = graph.node(binding.declared_at);
            BindingView {
                id: binding.id.index(),
                name: binding.name.clone(),
                kind: match binding.kind {
                    lash_kernel_check::BindingKind::Param => BindingKind::Param,
                    lash_kernel_check::BindingKind::Let => BindingKind::Let,
                    lash_kernel_check::BindingKind::For => BindingKind::For,
                    lash_kernel_check::BindingKind::Catch => BindingKind::Catch,
                },
                site: declaration.site.clone(),
                block: graph.node(graph.scope(binding.scope).block).site.clone(),
                ty: binding.facet.clone(),
                assigned: binding.assigned,
                captured: binding.captured,
                value_site: match declaration.kind {
                    NodeKind::Stmt(StmtNode::Let { value, .. })
                    | NodeKind::Expr(ExprNode::Let { value, .. }) => {
                        Some(graph.node(value).site.clone())
                    }
                    _ => None,
                },
                produced_by: producers.binding(binding.id),
                uses: uses.remove(&binding.id).unwrap_or_default(),
            }
        })
        .collect();
    view.dataflow.bindings = bindings;
    view.entry = entry::entry(document, entry, &view.dataflow.parameters, &view);
    coarse::project(document, graph, functions, &mut view, packages);
    Ok(view)
}

fn execution_site(site: &lash_kernel_check::ExecutionSite) -> ExecutionSiteView {
    use lash_kernel_check::SiteKind as Graph;
    ExecutionSiteView {
        site: site.site.clone(),
        statement: site.statement.clone(),
        within: site.within.clone(),
        kind: match site.kind {
            Graph::Call => SiteKind::Call,
            Graph::Perform => SiteKind::Perform,
            Graph::Sleep => SiteKind::Sleep,
            Graph::Join => SiteKind::Join,
            Graph::JoinMany => SiteKind::JoinMany,
            Graph::Yield => SiteKind::Yield,
            Graph::Spawn => SiteKind::Spawn,
            Graph::Cancel => SiteKind::Cancel,
            Graph::Await => SiteKind::Await,
        },
        loops: site.loops.clone(),
    }
}

fn mismatch(node: &GraphNode) -> ViewError {
    ViewError::Mismatch {
        site: node.site.clone(),
    }
}

/// What a `return` ends.
#[derive(Clone)]
struct Callable {
    site: Site,
    expected: Type,
}

/// Where the walk stands.
struct Context {
    block: Site,
    statement: Option<Site>,
    depth: usize,
    callable: Callable,
    /// What the enclosing statement writes, when it is an assignment.
    assigns: Option<Place>,
    /// What the node opens when it is a block.
    opens: Option<ScopeKind>,
}

struct Walk<'a> {
    packages: &'a PackageView<'a>,
    ordinals: BTreeMap<Site, u32>,
    document: &'a Document,
    graph: &'a Graph,
    functions: &'a FunctionDeclarations,
    entry: Callable,
    view: WorkflowView,
    uses: BTreeMap<BindingId, Vec<Use>>,
    links: applies::Links,
}

impl<'a> Walk<'a> {
    fn node(&mut self, id: NodeId, written: Node<'a>, at: &Context) -> Result<(), ViewError> {
        let graph = self.graph;
        let node = graph.node(id);
        for binding in direct_references(&node.kind) {
            self.uses.entry(binding).or_default().push(Use {
                site: node.site.clone(),
                statement: at.statement.clone().ok_or_else(|| mismatch(node))?,
            });
        }
        let mut inner = Context {
            block: at.block.clone(),
            statement: at.statement.clone(),
            depth: at.depth,
            callable: at.callable.clone(),
            assigns: None,
            opens: None,
        };
        // The blocks this node opens, each with what it is the body of.
        let mut opens: Vec<(NodeId, ScopeKind)> = Vec::new();
        match (&node.kind, written) {
            (NodeKind::Block(_), Node::Block(_)) => {
                let kind = at.opens.ok_or_else(|| mismatch(node))?;
                self.view.scopes.push(ScopeView {
                    ordinal: self.ordinals[&node.site],
                    block: node.site.clone(),
                    statement: at.statement.clone(),
                    depth: at.depth,
                    kind,
                });
                inner.block = node.site.clone();
            }
            (NodeKind::Stmt(statement), Node::Stmt(written)) => {
                self.statement(node, statement, written, at, &mut opens);
                inner.statement = Some(node.site.clone());
                inner.depth += 1;
                inner.assigns = match written {
                    Stmt::Assign { place, .. } => Some(place.clone()),
                    _ => None,
                };
            }
            (NodeKind::Action(action), Node::Action(written)) => {
                self.action(
                    node,
                    Derived::Statement(action),
                    Written::Statement(written),
                    at,
                )?;
            }
            (NodeKind::Expr(expression), Node::Expr(written)) => {
                self.view.dataflow.expressions.push(ExpressionView {
                    site: node.site.clone(),
                    statement: at.statement.clone().ok_or_else(|| mismatch(node))?,
                    block: at.block.clone(),
                    expression: written.clone(),
                    ty: node.facet.clone().unwrap_or(Type::Any),
                    references: references(graph, id),
                    available: available(graph, node),
                });
                match expression {
                    ExprNode::Closure { body, .. } => {
                        opens.push((*body, ScopeKind::Closure));
                        inner.callable = Callable {
                            site: node.site.clone(),
                            expected: match &node.facet {
                                Some(Type::Function(signature)) => signature.result.clone(),
                                _ => Type::Any,
                            },
                        };
                    }
                    ExprNode::Literal(_)
                    | ExprNode::Variable(_)
                    | ExprNode::Tuple(_)
                    | ExprNode::List(_)
                    | ExprNode::Map(_)
                    | ExprNode::Set(_)
                    | ExprNode::Record(_)
                    | ExprNode::Member(_)
                    | ExprNode::Call { .. }
                    | ExprNode::If { .. }
                    | ExprNode::Let { .. }
                    | ExprNode::Clock
                    | ExprNode::Random
                    | ExprNode::Read { .. } => {}
                    ExprNode::Act { kind, args } => {
                        let Expr::Act(act) = written else {
                            return Err(mismatch(node));
                        };
                        self.action(node, Derived::Nested(kind, args), Written::Nested(act), at)?;
                    }
                }
            }
            (
                NodeKind::Block(_) | NodeKind::Stmt(_) | NodeKind::Action(_) | NodeKind::Expr(_),
                _,
            ) => {
                return Err(mismatch(node));
            }
        }
        let children = node.children();
        let written = written.children();
        if children.len() != written.len() {
            return Err(mismatch(node));
        }
        for (child, written) in children.into_iter().zip(written) {
            inner.opens = opens
                .iter()
                .find(|(block, _)| *block == child)
                .map(|(_, kind)| *kind);
            self.node(child, written, &inner)?;
        }
        Ok(())
    }

    fn statement(
        &mut self,
        node: &GraphNode,
        statement: &StmtNode,
        written: &Stmt,
        at: &Context,
        opens: &mut Vec<(NodeId, ScopeKind)>,
    ) {
        let graph = self.graph;
        self.view.statements.push(StatementView {
            ordinal: self.ordinals[&node.site],
            site: node.site.clone(),
            statement: written.clone(),
            block: at.block.clone(),
            depth: at.depth,
            actions: issued(graph, node),
        });
        match statement {
            StmtNode::If {
                then_block,
                else_block,
                ..
            } => opens.extend([
                (*then_block, ScopeKind::Then),
                (*else_block, ScopeKind::Else),
            ]),
            StmtNode::For {
                body, else_block, ..
            } => {
                opens.push((*body, ScopeKind::For));
                opens.extend(else_block.map(|block| (block, ScopeKind::Else)));
            }
            StmtNode::While {
                body, else_block, ..
            } => {
                opens.push((*body, ScopeKind::While));
                opens.extend(else_block.map(|block| (block, ScopeKind::Else)));
            }
            StmtNode::Try {
                body,
                catch,
                finally,
            } => {
                opens.push((*body, ScopeKind::Try));
                opens.extend(catch.as_ref().map(|catch| (catch.body, ScopeKind::Catch)));
                opens.extend(finally.map(|finally| (finally, ScopeKind::Finally)));
            }
            StmtNode::Return { value }
            | StmtNode::ReturnVia { value, .. }
            | StmtNode::Finish { value } => {
                let callable = if matches!(statement, StmtNode::Finish { .. }) {
                    &self.entry
                } else {
                    &at.callable
                };
                let value = graph.node(*value);
                self.view.dataflow.returns.push(ReturnView {
                    callable: callable.site.clone(),
                    expected_type: callable.expected.clone(),
                    statement: node.site.clone(),
                    expression_site: value.site.clone(),
                    ty: value.facet.clone().unwrap_or(Type::Any),
                });
            }
            StmtNode::Assign { value, .. } => {
                if let Stmt::Assign { place, .. } = written {
                    self.view.dataflow.assignments.push(AssignmentView {
                        statement: node.site.clone(),
                        value_site: graph.node(*value).site.clone(),
                        destination: place.clone(),
                    });
                }
            }
            StmtNode::Let { .. }
            | StmtNode::Remove { .. }
            | StmtNode::Do { .. }
            | StmtNode::Break { .. }
            | StmtNode::Continue { .. }
            | StmtNode::Throw { .. }
            | StmtNode::Print { .. }
            | StmtNode::Fail { .. } => {}
        }
    }

    fn action(
        &mut self,
        node: &GraphNode,
        derived: Derived<'_>,
        written: Written<'_>,
        at: &Context,
    ) -> Result<(), ViewError> {
        let statement = at.statement.clone().ok_or_else(|| mismatch(node))?;
        // An `await` calls its policy (`K-TASK-026`).
        let awaited;
        let (callee, effect) = match written {
            Written::Statement(Action::Call { callee, .. } | Action::Spawn { callee, .. })
            | Written::Nested(ActExpr {
                kind: ActKind::Call(callee) | ActKind::Spawn(callee),
                ..
            }) => (Some(callee), None),
            Written::Statement(Action::Await { policy, .. })
            | Written::Nested(ActExpr {
                kind: ActKind::Await(policy),
                ..
            }) => {
                awaited = Callee::Library(*policy);
                (Some(&awaited), None)
            }
            Written::Statement(Action::Perform { effect, .. })
            | Written::Nested(ActExpr {
                kind: ActKind::Perform { effect, .. },
                ..
            }) => (None, Some(effect)),
            Written::Statement(_) | Written::Nested(_) => (None, None),
        };
        let signature = effect.and_then(|effect| self.document.manifest.effects.get(effect));
        let (callee, params) = match (callee, effect) {
            (Some(Callee::Library(function)), _) => {
                let definition =
                    self.functions
                        .get(function)
                        .ok_or(ViewError::MissingFunction {
                            function: *function,
                        })?;
                (
                    Some(CalleeView::Library {
                        id: *function,
                        member: self
                            .packages
                            .members(function)
                            .into_iter()
                            .map(|(package, member)| PackageMemberView { package, member })
                            .collect(),
                        name: self
                            .document
                            .manifest
                            .functions
                            .get(function)
                            .cloned()
                            .ok_or_else(|| mismatch(node))?,
                    }),
                    definition.signature.params.clone(),
                )
            }
            (Some(Callee::Declared(name)), _) => {
                let function = self
                    .document
                    .functions
                    .get(name)
                    .ok_or_else(|| mismatch(node))?;
                let params = self.document.entries.get(name).map_or_else(
                    || {
                        function
                            .params
                            .iter()
                            .map(|name| Param {
                                name: name.clone(),
                                ty: Type::Any,
                                optional: false,
                            })
                            .collect()
                    },
                    |entry| entry.signature.params.clone(),
                );
                (Some(CalleeView::Declared(name.clone())), params)
            }
            (Some(Callee::Value(_)), _) => (None, Vec::new()),
            (None, Some(effect)) => (
                Some(CalleeView::Effect(effect.clone())),
                signature.map_or_else(Vec::new, |required| required.signature.params.clone()),
            ),
            (None, None) => (None, Vec::new()),
        };
        // The operand a builtin action names its one argument.
        let operand = match written {
            Written::Statement(Action::Sleep { .. })
            | Written::Nested(ActExpr {
                kind: ActKind::Sleep { .. },
                ..
            }) => Some("duration"),
            Written::Statement(Action::Join { .. } | Action::Cancel { .. })
            | Written::Nested(ActExpr {
                kind: ActKind::Join | ActKind::Cancel,
                ..
            }) => Some("task"),
            Written::Statement(Action::JoinMany { .. })
            | Written::Nested(ActExpr {
                kind: ActKind::JoinMany(_),
                ..
            }) => Some("tasks"),
            Written::Statement(Action::Await { .. })
            | Written::Nested(ActExpr {
                kind: ActKind::Await(_),
                ..
            }) => Some("value"),
            Written::Statement(_) | Written::Nested(_) => None,
        };
        let arguments: Vec<(Expr, Option<Site>, Option<usize>)> = match (written, derived) {
            (Written::Statement(written), Derived::Statement(derived)) => written_atoms(written)
                .into_iter()
                .zip(atoms(derived))
                .map(|(atom, derived)| {
                    let expression = match atom {
                        Atom::Variable(name) => Expr::Variable(name.clone()),
                        Atom::Literal(literal) => Expr::Literal(literal.clone()),
                    };
                    let binding = match derived {
                        AtomNode::Variable(Reference::Binding(id)) => Some(id.index()),
                        AtomNode::Variable(Reference::Session(_)) | AtomNode::Literal(_) => None,
                    };
                    (expression, None, binding)
                })
                .collect(),
            (Written::Nested(written), Derived::Nested(_, args)) => written
                .args
                .iter()
                .zip(args)
                .map(|(expression, id)| {
                    let arg = self.graph.node(*id);
                    let binding = match arg.kind {
                        NodeKind::Expr(ExprNode::Variable(Reference::Binding(id))) => {
                            Some(id.index())
                        }
                        _ => None,
                    };
                    (expression.clone(), Some(arg.site.clone()), binding)
                })
                .collect(),
            (Written::Statement(_) | Written::Nested(_), _) => return Err(mismatch(node)),
        };
        let args = arguments
            .into_iter()
            .enumerate()
            .map(|(index, (expression, site, binding))| {
                let param = params.get(index);
                ArgumentView {
                    name: param
                        .map(|param| param.name.clone())
                        .or_else(|| operand.map(Name::new)),
                    ty: param.map_or(Type::Any, |param| param.ty.clone()),
                    expression,
                    site,
                    binding,
                }
            })
            .collect();
        let kind = match derived {
            Derived::Statement(action) => match action {
                ActionNode::Call { .. } => SiteKind::Call,
                ActionNode::Perform { .. } => SiteKind::Perform,
                ActionNode::Sleep { .. } => SiteKind::Sleep,
                ActionNode::Join { .. } => SiteKind::Join,
                ActionNode::JoinMany { .. } => SiteKind::JoinMany,
                ActionNode::Yield => SiteKind::Yield,
                ActionNode::Spawn { .. } => SiteKind::Spawn,
                ActionNode::Cancel { .. } => SiteKind::Cancel,
                ActionNode::Await { .. } => SiteKind::Await,
            },
            Derived::Nested(kind, _) => match kind {
                ActNode::Call(_) => SiteKind::Call,
                ActNode::Perform { .. } => SiteKind::Perform,
                ActNode::Sleep => SiteKind::Sleep,
                ActNode::Spawn(_) => SiteKind::Spawn,
                ActNode::Yield => SiteKind::Yield,
                ActNode::Cancel => SiteKind::Cancel,
                ActNode::Join => SiteKind::Join,
                ActNode::JoinMany(_) => SiteKind::JoinMany,
                ActNode::Await(_) => SiteKind::Await,
            },
        };
        let result_type = match derived {
            Derived::Statement(ActionNode::Perform {
                result: Type::Any, ..
            })
            | Derived::Nested(
                ActNode::Perform {
                    result: Type::Any, ..
                },
                _,
            ) => signature.map_or(Type::Any, |required| required.signature.result.clone()),
            _ => node.facet.clone().unwrap_or(Type::Any),
        };
        let role = match (kind, &callee) {
            (SiteKind::Perform, _) => ActionRole::Effect,
            (SiteKind::Sleep, _) => ActionRole::Wait,
            (SiteKind::Call | SiteKind::Spawn, Some(CalleeView::Library { .. }))
            | (SiteKind::Await, _) => ActionRole::Library,
            (SiteKind::Call | SiteKind::Spawn, _) => ActionRole::SubWorkflow,
            (SiteKind::Join | SiteKind::JoinMany | SiteKind::Cancel | SiteKind::Yield, _) => {
                ActionRole::Task
            }
        };
        let applies = self.links.applies(self.graph, self.functions, derived);
        let mut performs = match &callee {
            Some(CalleeView::Effect(effect)) => std::collections::BTreeSet::from([effect.clone()]),
            Some(CalleeView::Library { id, .. }) => library_performs(self.functions, id),
            Some(CalleeView::Declared(name)) => self
                .graph
                .unit(&Unit::Function(name.clone()))
                .map(|unit| unit.effects.effects.clone())
                .unwrap_or_default(),
            None => std::collections::BTreeSet::new(),
        };
        performs.extend(applied_performs(
            self.graph,
            self.functions,
            &mut self.links,
            &applies,
        ));
        self.view.dataflow.actions.push(ActionView {
            site: node.site.clone(),
            kind,
            role,
            statement,
            block: at.block.clone(),
            destination: at.assigns.clone(),
            callee,
            applies,
            performs: performs.into_iter().collect(),
            args,
            result_type,
            available: available(self.graph, node),
        });
        Ok(())
    }
}

/// Project reached callback bodies without attributing unrelated closures in
/// their containing unit. Library and declared recursion remain the checker's
/// derivation; the view only follows the callable sites `applies` has resolved.
fn applied_performs(
    graph: &Graph,
    functions: &FunctionDeclarations,
    links: &mut applies::Links,
    callables: &[Site],
) -> std::collections::BTreeSet<EffectName> {
    use std::collections::BTreeSet;
    let mut effects = BTreeSet::new();
    let mut callables = callables.to_vec();
    let mut seen = BTreeSet::new();
    while let Some(site) = callables.pop() {
        if !seen.insert(site.clone()) {
            continue;
        }
        if site.path.is_empty() {
            if let Some(unit) = graph.unit(&site.unit) {
                effects.extend(unit.effects.effects.iter().cloned());
            }
            continue;
        }
        let Some(root) = graph.node_at(&site) else {
            continue;
        };
        let mut pending = root.children();
        while let Some(id) = pending.pop() {
            let node = graph.node(id);
            if matches!(node.kind, NodeKind::Expr(ExprNode::Closure { .. })) {
                continue;
            }
            let action = match &node.kind {
                NodeKind::Action(action) => Some(Derived::Statement(action)),
                NodeKind::Expr(ExprNode::Act { kind, args }) => Some(Derived::Nested(kind, args)),
                _ => None,
            };
            let callee = match action {
                Some(Derived::Statement(ActionNode::Perform { effect, .. }))
                | Some(Derived::Nested(ActNode::Perform { effect, .. }, _)) => {
                    effects.insert(effect.clone());
                    None
                }
                Some(Derived::Statement(
                    ActionNode::Call { callee, .. } | ActionNode::Spawn { callee, .. },
                ))
                | Some(Derived::Nested(ActNode::Call(callee) | ActNode::Spawn(callee), _)) => {
                    Some(callee.clone())
                }
                Some(Derived::Statement(ActionNode::Await { policy, .. }))
                | Some(Derived::Nested(ActNode::Await(policy), _)) => {
                    Some(CalleeNode::Library(*policy))
                }
                _ => None,
            };
            match callee {
                Some(CalleeNode::Library(id)) => effects.extend(library_performs(functions, &id)),
                Some(CalleeNode::Declared(name)) => {
                    if let Some(unit) = graph.unit(&Unit::Function(name)) {
                        effects.extend(unit.effects.effects.iter().cloned());
                    }
                }
                _ => {}
            }
            if let Some(action) = action {
                callables.extend(links.applies(graph, functions, action));
            }
            match &node.kind {
                NodeKind::Expr(ExprNode::Call { function, .. })
                | NodeKind::Stmt(StmtNode::ReturnVia {
                    policy: function, ..
                }) => effects.extend(library_performs(functions, function)),
                _ => {}
            }
            pending.extend(node.children());
        }
    }
    effects
}

/// An action as the checker derived it.
#[derive(Clone, Copy)]
pub(crate) enum Derived<'a> {
    Statement(&'a ActionNode),
    Nested(&'a ActNode, &'a [NodeId]),
}

/// An action as the document writes it.
#[derive(Clone, Copy)]
enum Written<'a> {
    Statement(&'a Action),
    Nested(&'a ActExpr),
}

/// The sites of the actions a statement issues, in the order it issues
/// them: each action after its arguments, children left to right. The
/// blocks it holds are statements of their own.
fn issued(graph: &Graph, statement: &GraphNode) -> Vec<Site> {
    fn walk(graph: &Graph, node: &GraphNode, out: &mut Vec<Site>) {
        for child in node.children() {
            let child = graph.node(child);
            if !matches!(child.kind, NodeKind::Block(_)) {
                walk(graph, child, out);
            }
        }
        if matches!(
            node.kind,
            NodeKind::Action(_) | NodeKind::Expr(ExprNode::Act { .. })
        ) {
            out.push(node.site.clone());
        }
    }
    let mut out = Vec::new();
    let mut children = statement.children();
    // K-EVAL-003: a value-first assignment evaluates its right-hand side
    // before its member place, unlike Site order.
    if matches!(
        statement.kind,
        NodeKind::Stmt(StmtNode::Assign {
            order: AssignOrder::ValueFirst,
            ..
        })
    ) && children.len() > 1
    {
        children.rotate_right(1);
    }
    for child in children {
        let child = graph.node(child);
        if !matches!(child.kind, NodeKind::Block(_)) {
            walk(graph, child, &mut out);
        }
    }
    out
}

/// The bindings a node names itself, not through its children. The target
/// of an assignment is a write, not a read.
fn direct_references(kind: &NodeKind) -> Vec<BindingId> {
    let references: Vec<&Reference> = match kind {
        NodeKind::Expr(expression) => match expression {
            ExprNode::Variable(reference) => vec![reference],
            ExprNode::Closure { captures, .. } => captures.iter().collect(),
            ExprNode::Act {
                kind:
                    ActNode::Call(CalleeNode::Value(reference))
                    | ActNode::Spawn(CalleeNode::Value(reference)),
                ..
            } => vec![reference],
            ExprNode::Act { .. } => Vec::new(),
            ExprNode::Literal(_)
            | ExprNode::Tuple(_)
            | ExprNode::List(_)
            | ExprNode::Map(_)
            | ExprNode::Set(_)
            | ExprNode::Record(_)
            | ExprNode::Member(_)
            | ExprNode::Call { .. }
            | ExprNode::If { .. }
            | ExprNode::Let { .. }
            | ExprNode::Clock
            | ExprNode::Random
            | ExprNode::Read { .. } => Vec::new(),
        },
        NodeKind::Action(action) => {
            let callee = match action {
                ActionNode::Call { callee, .. } | ActionNode::Spawn { callee, .. } => {
                    match callee {
                        CalleeNode::Value(reference) => Some(reference),
                        CalleeNode::Declared(_) | CalleeNode::Library(_) => None,
                    }
                }
                ActionNode::Perform { .. }
                | ActionNode::Sleep { .. }
                | ActionNode::Join { .. }
                | ActionNode::JoinMany { .. }
                | ActionNode::Yield
                | ActionNode::Cancel { .. }
                | ActionNode::Await { .. } => None,
            };
            callee
                .into_iter()
                .chain(atoms(action).into_iter().filter_map(|atom| match atom {
                    AtomNode::Variable(reference) => Some(reference),
                    AtomNode::Literal(_) => None,
                }))
                .collect()
        }
        NodeKind::Stmt(_) | NodeKind::Block(_) => Vec::new(),
    };
    references
        .into_iter()
        .filter_map(|reference| match reference {
            Reference::Binding(id) => Some(*id),
            Reference::Session(_) => None,
        })
        .collect()
}

fn atoms(action: &ActionNode) -> Vec<&AtomNode> {
    match action {
        ActionNode::Call { args, .. }
        | ActionNode::Spawn { args, .. }
        | ActionNode::Perform { args, .. } => args.iter().collect(),
        ActionNode::Sleep { duration } => vec![duration],
        ActionNode::Join { task } | ActionNode::Cancel { task } => vec![task],
        ActionNode::JoinMany { tasks, .. } => vec![tasks],
        ActionNode::Await { value, .. } => vec![value],
        ActionNode::Yield => vec![],
    }
}

fn written_atoms(action: &Action) -> Vec<&Atom> {
    match action {
        Action::Call { args, .. } | Action::Spawn { args, .. } | Action::Perform { args, .. } => {
            args.iter().collect()
        }
        Action::Sleep { duration, .. } => vec![duration],
        Action::Join { task } | Action::Cancel { task } => vec![task],
        Action::JoinMany { tasks, .. } => vec![tasks],
        Action::Await { value, .. } => vec![value],
        Action::Yield => vec![],
    }
}

/// The bindings a node and its children read, in id order. A closure's body
/// reads for the closure through its captures.
fn references(graph: &Graph, id: NodeId) -> Vec<usize> {
    fn collect(graph: &Graph, id: NodeId, out: &mut std::collections::BTreeSet<usize>) {
        let node = graph.node(id);
        out.extend(
            direct_references(&node.kind)
                .into_iter()
                .map(BindingId::index),
        );
        if !matches!(node.kind, NodeKind::Expr(ExprNode::Closure { .. })) {
            for child in node.children() {
                collect(graph, child, out);
            }
            if let NodeKind::Expr(ExprNode::Let { binding, .. }) = node.kind {
                out.remove(&binding.index());
            }
        }
    }
    let mut out = std::collections::BTreeSet::new();
    collect(graph, id, &mut out);
    out.into_iter().collect()
}

/// The binding each name resolves to at `node`, as lexical lookup would: a
/// binding declared at or after the node, or whose `let` holds it, is not
/// yet visible, and an inner binding shadows an outer one of its name.
fn available(graph: &Graph, node: &GraphNode) -> Vec<usize> {
    let mut scope = Some(node.scope);
    let mut names = BTreeMap::new();
    while let Some(id) = scope {
        let current = graph.scope(id);
        for binding_id in current.bindings.iter().rev() {
            let binding = graph.binding(*binding_id);
            let declaration = graph.node(binding.declared_at);
            if binding.kind == lash_kernel_check::BindingKind::Let
                && !matches!(declaration.kind, NodeKind::Expr(ExprNode::Let { .. }))
                && (declaration.id.index() >= node.id.index()
                    || (declaration.site.unit == node.site.unit
                        && node.site.path.starts_with(&declaration.site.path)))
            {
                continue;
            }
            names
                .entry(binding.name.clone())
                .or_insert(binding.id.index());
        }
        scope = current.parent;
    }
    names.into_values().collect()
}

