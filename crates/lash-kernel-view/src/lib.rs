//! The canvas read of one entry of a document: what a host draws and edits
//! against, with no presentation.
//!
//! [`derive`] projects a checked [`WorkflowDocument`] (its document, the
//! [`Graph`] the checker derived from it and the library declarations it
//! linked against) into a [`WorkflowView`]: canonical action, control and code
//! nodes, lexical callable roots, control roles and exact flow destinations.
//! Statements, scopes, dataflow and execution sites support selection and ports;
//! hosts render the supplied nodes. Action issue order follows runtime evaluation,
//! including a value-first assignment's RHS before its place, rather than
//! universal child order.
//! Canonical printer lines and optional readable-lens ranges belong to this
//! document revision. Every kernel form is matched here, so a new form fails to
//! compile here instead of requiring a host to learn it.
//!
//! The view is data. It serialises, and its schema is the
//! `kernel-workflow-view` host schema. Ids name bindings within one
//! derivation; edits address sites, never these ids. A library callee
//! carries its identity and the name its `use` line gives it; display
//! labels are read from the explicitly supplied package view. Layout, styling and
//! templates are the host's.
//!
//! [`JSON_SCHEMA`] is self-contained: every `$ref` has the form
//! `#/$defs/<name>` and resolves within its root `$defs`, with no external or
//! `$id`-relative references. Definition names are stable within a lash
//! version, so hosts may splice the definitions into their own OpenAPI schemas.
//!
//! The caller supplies a [`PackageView`] of the cell's installed set for
//! surface membership and display facts, including comparison and reply markers.
//! Reading a view links no dialect implementation, editor or runtime.

